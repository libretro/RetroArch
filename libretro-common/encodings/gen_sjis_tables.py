# python3 gen_sjis_tables.py > encoding_shiftjis_tables.h
#
# Writes encoding_shiftjis_tables.h: Shift-JIS as Windows code page 932
# has it (JIS X 0208 with the NEC and IBM extensions), from Python's
# cp932 codec. The user-defined area F040-F9FC and the single octets
# 0x80, 0xA0 and 0xFD-0xFF, which code page 932 sends to the Private Use
# Area, are left out.
import sys

def lead_ok(l):
    return 0x81 <= l <= 0x9F or 0xE0 <= l <= 0xEF or 0xFA <= l <= 0xFC

leads = [l for l in range(0x81, 0xFD) if lead_ok(l)]
decode = []
pairs = {}
for l in leads:
    row = []
    for t in range(0x40, 0xFD):
        u = 0
        try:
            s = bytes([l, t]).decode('cp932')
            if len(s) == 1 and not (0xE000 <= ord(s) <= 0xF8FF):
                u = ord(s)
        except UnicodeDecodeError:
            pass
        row.append(u)
    decode.append(row)

for cp in range(0x80, 0x10000):
    if 0xD800 <= cp < 0xE000 or 0xE000 <= cp <= 0xF8FF:
        continue
    try:
        e = chr(cp).encode('cp932')
    except UnicodeEncodeError:
        continue
    if len(e) == 2 and lead_ok(e[0]):
        pairs[cp] = (e[0] << 8) | e[1]

out = sys.stdout
out.write('/* Generated by gen_sjis_tables.py from code page 932, as Python\'s\n'
          ' * cp932 codec has it; do not edit. */\n'
          '#ifndef LIBRETRO_ENCODING_SHIFTJIS_TABLES_H\n'
          '#define LIBRETRO_ENCODING_SHIFTJIS_TABLES_H\n\n'
          '#include <stdint.h>\n\n')
out.write('/* Unicode for lead octet L (rows: 0x81-0x9F, 0xE0-0xEF, 0xFA-0xFC)\n'
          ' * and trail octet 0x40-0xFC; 0 where nothing is mapped. */\n')
out.write('static const uint16_t sjis_decode[%d][189] = {\n' % len(leads))
for l, row in zip(leads, decode):
    out.write('   /* 0x%02X */ {\n' % l)
    for i in range(0, len(row), 10):
        out.write('      ' + ','.join('0x%04X' % v for v in row[i:i+10]) + ',\n')
    out.write('   },\n')
out.write('};\n\n')
keys = sorted(pairs)
out.write('/* Unicode code points with their two-octet Shift-JIS codes, sorted\n'
          ' * by code point for a binary search. */\n')
out.write('#define SJIS_ENCODE_COUNT %d\n' % len(keys))
out.write('static const uint16_t sjis_encode[SJIS_ENCODE_COUNT][2] = {\n')
for i in range(0, len(keys), 6):
    out.write('   ' + ','.join('{0x%04X,0x%04X}' % (k, pairs[k]) for k in keys[i:i+6]) + ',\n')
out.write('};\n\n#endif\n')
