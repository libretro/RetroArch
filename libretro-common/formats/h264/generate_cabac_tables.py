"""Generate CABAC data from a pinned BSD-2-Clause OpenH264 source.

Download SOURCE_URL, then pass that local file. No network access is performed
by this tool. --check compares the generated header without writing it.
The extension ranges follow H.264 (08/2024) Tables 9-25 through 9-33.
"""
import argparse
import hashlib
from pathlib import Path
import re

SOURCE_URL = "https://raw.githubusercontent.com/cisco/openh264/1bca62311e447fd9c39fc93de2c4b96cd5ce971c/codec/common/src/common_tables.cpp"
SOURCE_SHA256 = "2cf0a5fc3fce813413566af2ced506eb91a1e0c3f625abc9ca9bf70e0ffef958"
NOTICE = 'Copyright (c) 2013, Cisco Systems\nAll rights reserved.\n\nRedistribution and use in source and binary forms, with or without modification,\nare permitted provided that the following conditions are met:\n\n* Redistributions of source code must retain the above copyright notice, this\n  list of conditions and the following disclaimer.\n\n* Redistributions in binary form must reproduce the above copyright notice, this\n  list of conditions and the following disclaimer in the documentation and/or\n  other materials provided with the distribution.\n\nTHIS SOFTWARE IS PROVIDED BY THE COPYRIGHT HOLDERS AND CONTRIBUTORS "AS IS" AND\nANY EXPRESS OR IMPLIED WARRANTIES, INCLUDING, BUT NOT LIMITED TO, THE IMPLIED\nWARRANTIES OF MERCHANTABILITY AND FITNESS FOR A PARTICULAR PURPOSE ARE\nDISCLAIMED. IN NO EVENT SHALL THE COPYRIGHT HOLDER OR CONTRIBUTORS BE LIABLE FOR\nANY DIRECT, INDIRECT, INCIDENTAL, SPECIAL, EXEMPLARY, OR CONSEQUENTIAL DAMAGES\n(INCLUDING, BUT NOT LIMITED TO, PROCUREMENT OF SUBSTITUTE GOODS OR SERVICES;\nLOSS OF USE, DATA, OR PROFITS; OR BUSINESS INTERRUPTION) HOWEVER CAUSED AND ON\nANY THEORY OF LIABILITY, WHETHER IN CONTRACT, STRICT LIABILITY, OR TORT\n(INCLUDING NEGLIGENCE OR OTHERWISE) ARISING IN ANY WAY OUT OF THE USE OF THIS\nSOFTWARE, EVEN IF ADVISED OF THE POSSIBILITY OF SUCH DAMAGE.'
# destination, base context, count; H.264 Tables 9-25..9-33.
RANGES = (
    (460, 85, 12), (472, 85, 12),
    (484, 105, 44), (528, 105, 44),
    (572, 166, 44), (616, 166, 44),
    (660, 402, 15), (675, 436, 15),
    (690, 417, 9), (699, 451, 9), (708, 426, 10),
    (718, 402, 15), (733, 436, 15),
    (748, 417, 9), (757, 451, 9), (766, 426, 10),
    (776, 277, 44), (820, 277, 44),
    (864, 338, 44), (908, 338, 44),
    (952, 227, 30), (982, 227, 30),
    (1012, 93, 4), (1016, 93, 4), (1020, 93, 4),
)


def generate(source):
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("input is not the pinned OpenH264 common_tables.cpp")
    text = source.decode("utf-8")
    start = text.index("const int8_t g_kiCabacGlobalContextIdx")
    text = text[start:text.index("};", start)]
    text = re.sub(r"//[^\n]*", "", text)
    pairs = re.findall(r"\{\s*(-?\d+|CTX_NA)\s*,\s*(-?\d+|CTX_NA)\s*\}", text)
    pairs = [tuple(0 if x == "CTX_NA" else int(x) for x in pair) for pair in pairs]
    if len(pairs) != 460 * 4:
        raise ValueError("unexpected OpenH264 table dimensions")
    tables = [[pairs[4 * i + variant] for i in range(460)] for variant in range(4)]
    for destination, base, count in RANGES:
        for table in tables:
            if len(table) != destination:
                raise ValueError("non-contiguous extension")
            table.extend(table[base:base + count])
    lines = ["/* SPDX-License-Identifier: BSD-2-Clause",
             " * Generated by generate_cabac_tables.py; do not edit.",
             " * Source: " + SOURCE_URL]
    lines.extend(" * " + line if line else " *" for line in NOTICE.splitlines())
    lines.extend([" */", "", "#define RH264_CABAC_NCTX 1024"])
    lines.append("static const int8_t rh264_cabac_init_I[1024][2]={")
    for table_index, table in enumerate(tables):
        if len(table) != 1024:
            raise ValueError("unexpected output dimensions")
        if table_index == 1:
            lines.extend(["};", "static const int8_t rh264_cabac_init_PB[3][1024][2]={"])
        if table_index:
            lines.append(" {")
        for offset in range(0, 1024, 8):
            lines.append("  " + ",".join("{%d,%d}" % pair for pair in table[offset:offset + 8]) + ",")
        if table_index:
            lines.append(" },")
    lines.extend(["};", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = Path(__file__).with_name("rh264_cabac_tables.h")
    expected = generate(args.source.read_bytes())
    if args.check:
        if output.read_text(encoding="utf-8") != expected:
            raise SystemExit("generated header differs")
        print("CABAC header matches pinned BSD source and specification mappings")
    else:
        output.write_bytes(expected.encode("utf-8"))


if __name__ == "__main__":
    main()
