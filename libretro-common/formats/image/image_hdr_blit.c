/* Native 10-bit I420 -> XRGB2101010 (packed 2-10-10-10, native endian) */
/* Produces the SAME SDR-encoded colour as the _hbd path - PQ/HDR10 is  */
/* tone-mapped (hable), BT.2020 -> 709 gamut, sRGB transfer - but keeps  */
/* 10-bit precision instead of narrowing to 8, so gradients are smoother */
/* with less banding. The frontend's HDR pipeline expects an SDR-encoded */
/* source (it inverse-tone-maps SDR -> HDR for the display), so this     */
/* deliberately does NOT pass PQ through; it only raises the source bit  */
/* depth. Used when the frontend accepts RETRO_PIXEL_FORMAT_XRGB2101010. */
/* ------------------------------------------------------------------ */
void rwebm_video_blit_i420_10bit(uint32_t *dst, unsigned dst_stride,
      unsigned w, unsigned h, const uint16_t *y, int ys,
      const uint16_t *u, const uint16_t *v, int uvs,
      unsigned matrix, unsigned transfer, unsigned range,
      unsigned max_cll)
{
   int re, gd, ge, bd;
   /* PQ and HLG are HDR, tone-mapped to SDR; anything else is SDR */
   const uint16_t *hdr_lut = (transfer == 16) ? rwebm_hbd_pq_lut
                           : (transfer == 18) ? rwebm_hbd_hlg_lut : NULL;
   int is_pq   = (transfer == 16);
   int full    = (range == 2);
   unsigned j, i;

   if (!rwebm_hbd_lut_ready || (is_pq && max_cll != rwebm_hbd_lut_peak))
      rwebm_hbd_init_luts(max_cll);
   rwebm_hbd_matrix(matrix ? matrix : (hdr_lut ? 9u : 1u), &re, &gd, &ge, &bd);

   for (j = 0; j < h; j++)
   {
      const uint16_t *yr = y + (size_t)j * ys;
      const uint16_t *ur = u + (size_t)(j >> 1) * uvs;
      const uint16_t *vr = v + (size_t)(j >> 1) * uvs;
      uint32_t       *dr = dst + (size_t)j * dst_stride;
      for (i = 0; i < w; i++)
      {
         int c, d, e, r, g, b;
         if (full)
         {
            c = ((int)yr[i] * 877) >> 10;
            d = (((int)ur[i >> 1] - 512) * 897) >> 10;
            e = (((int)vr[i >> 1] - 512) * 897) >> 10;
         }
         else
         {
            c = (int)yr[i] - 64;
            d = (int)ur[i >> 1] - 512;
            e = (int)vr[i >> 1] - 512;
         }
         r = (298 * c + re * e + 128) >> 8;
         g = (298 * c - gd * d - ge * e + 128) >> 8;
         b = (298 * c + bd * d + 128) >> 8;
         if (r < 0) r = 0; else if (r > 1023) r = 1023;
         if (g < 0) g = 0; else if (g > 1023) g = 1023;
         if (b < 0) b = 0; else if (b > 1023) b = 1023;
         if (hdr_lut)
         {
            /* tone-mapped linear, then 2020 -> 709 gamut, then sRGB,
             * emitted at 10-bit precision. */
            int lr = hdr_lut[r];
            int lg = hdr_lut[g];
            int lb = hdr_lut[b];
            int xr = (6801 * lr - 2407 * lg -  298 * lb) >> 12;
            int xg = ( -510 * lr + 4640 * lg -   34 * lb) >> 12;
            int xb = (  -75 * lr -  412 * lg + 4583 * lb) >> 12;
            if (xr < 0) xr = 0; else if (xr > 65535) xr = 65535;
            if (xg < 0) xg = 0; else if (xg > 65535) xg = 65535;
            if (xb < 0) xb = 0; else if (xb > 65535) xb = 65535;
            r = rwebm_hbd_out_lut10[xr >> 3];
            g = rwebm_hbd_out_lut10[xg >> 3];
            b = rwebm_hbd_out_lut10[xb >> 3];
         }
         /* non-PQ: r/g/b are already 10-bit SDR-encoded, keep as-is */
         /* Pack XRGB2101010: bits [29:20]=R [19:10]=G [9:0]=B; top 2
          * bits set so the value reads opaque under an A2 interpretation. */
         dr[i] = ((uint32_t)r << 20)
               | ((uint32_t)g << 10)
               |  (uint32_t)b
               | 0xC0000000u;
      }
   }
}

/* ------------------------------------------------------------------ */
/* 10-bit HDR I420 -> linear scRGB, RGBA half floats.                  */
/* PQ is taken to absolute nits by its EOTF and HLG to display light   */
/* by its inverse OETF and a 1000-nit OOTF on the pixel's luminance;   */
/* either is then scaled so 80 nits is 1.0 and moved from BT.2020 to   */
/* the scRGB (709) primaries. No tone map, and no clamp: a colour      */
/* outside 709 keeps its negative components, which is how scRGB       */
/* carries the wider gamut.                                            */
/* ------------------------------------------------------------------ */

/* Nearest half float to @f, clamped to the largest finite one. */
static uint16_t image_hdr_half(float f)
{
   union { float f; uint32_t u; } v;
   uint32_t sign, mant, h;
   int exp;

   v.f  = f;
   sign = (v.u >> 16) & 0x8000u;
   exp  = (int)((v.u >> 23) & 0xffu) - 127 + 15;
   mant = v.u & 0x7fffffu;
   if (exp >= 31)
      return (uint16_t)(sign | 0x7bffu);
   if (exp <= 0)
   {
      unsigned shift;
      if (exp < -10)
         return (uint16_t)sign;
      mant |= 0x800000u;
      shift = (unsigned)(14 - exp);
      h     = mant >> shift;
      if ((mant >> (shift - 1)) & 1u)
         h++;
      return (uint16_t)(sign | h);
   }
   h = ((uint32_t)exp << 10) | (mant >> 13);
   if (mant & 0x1000u)
      h++;
   return (uint16_t)(sign | h);
}

int rwebm_video_blit_i420_fp16(uint16_t *dst, unsigned dst_stride,
      unsigned w, unsigned h, const uint16_t *y, int ys,
      const uint16_t *u, const uint16_t *v, int uvs,
      unsigned matrix, unsigned transfer, unsigned range)
{
   int re, gd, ge, bd;
   int full   = (range == 2);
   int is_hlg = (transfer == 18);
   unsigned j, i;

   if (transfer != 16 && !is_hlg)
      return 0;
   rwebm_hbd_matrix(matrix ? matrix : 9u, &re, &gd, &ge, &bd);

   for (j = 0; j < h; j++)
   {
      const uint16_t *yr = y + (size_t)j * ys;
      const uint16_t *ur = u + (size_t)(j >> 1) * uvs;
      const uint16_t *vr = v + (size_t)(j >> 1) * uvs;
      uint16_t       *dr = dst + (size_t)j * dst_stride * 4;
      for (i = 0; i < w; i++)
      {
         int c, d, e, r, g, b;
         float lr, lg, lb;
         if (full)
         {
            c = ((int)yr[i] * 877) >> 10;
            d = (((int)ur[i >> 1] - 512) * 897) >> 10;
            e = (((int)vr[i >> 1] - 512) * 897) >> 10;
         }
         else
         {
            c = (int)yr[i] - 64;
            d = (int)ur[i >> 1] - 512;
            e = (int)vr[i >> 1] - 512;
         }
         r = (298 * c + re * e + 128) >> 8;
         g = (298 * c - gd * d - ge * e + 128) >> 8;
         b = (298 * c + bd * d + 128) >> 8;
         if (r < 0) r = 0; else if (r > 1023) r = 1023;
         if (g < 0) g = 0; else if (g > 1023) g = 1023;
         if (b < 0) b = 0; else if (b > 1023) b = 1023;
         if (is_hlg)
         {
            /* Scene light, then the BT.2100 OOTF for a 1000-nit
             * display: Lw * Ys^(gamma - 1) per channel, gamma 1.2. */
            float er = image_hdr_hlg_scene[r];
            float eg = image_hdr_hlg_scene[g];
            float eb = image_hdr_hlg_scene[b];
            float ys_ = 0.2627f * er + 0.6780f * eg + 0.0593f * eb;
            float k   = ys_ > 0.0f
               ? (float)(1000.0 / 80.0 * pow((double)ys_, 0.2)) : 0.0f;
            lr = er * k;
            lg = eg * k;
            lb = eb * k;
         }
         else
         {
            lr = image_hdr_pq_scrgb[r];
            lg = image_hdr_pq_scrgb[g];
            lb = image_hdr_pq_scrgb[b];
         }
         dr[i * 4 + 0] = image_hdr_half( 1.660491f * lr - 0.587641f * lg - 0.072850f * lb);
         dr[i * 4 + 1] = image_hdr_half(-0.124550f * lr + 1.132900f * lg - 0.008349f * lb);
         dr[i * 4 + 2] = image_hdr_half(-0.018151f * lr - 0.100579f * lg + 1.118730f * lb);
         dr[i * 4 + 3] = 0x3c00u; /* 1.0 */
      }
   }
   return 1;
}
