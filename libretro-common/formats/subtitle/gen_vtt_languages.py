#!/usr/bin/env python3
"""Generate WebVTT language aliases from an IANA Language Subtag Registry snapshot."""
import argparse
import hashlib
import re
from pathlib import Path


def generate(raw):
    text = raw.decode("utf-8")
    blocks = text.split("%%")
    date = blocks.pop(0).strip()
    assert re.fullmatch(r"File-Date: [0-9]{4}-[0-9]{2}-[0-9]{2}", date)
    kinds = {"language": 0, "extlang": 1, "script": 2, "region": 3,
             "variant": 4, "grandfathered": 5, "redundant": 5}
    records = {}
    seen = set()
    for block in blocks:
        record = {}
        last = None
        for line in block.strip().splitlines():
            if line.startswith(" "):
                assert last
                record[last][-1] += " " + line.strip()
            else:
                last, value = line.split(": ", 1)
                record.setdefault(last, []).append(value)
        assert len(record["Type"]) == 1
        kind = record["Type"][0]
        assert kind in kinds
        field = "Tag" if kind in ("grandfathered", "redundant") else "Subtag"
        assert len(record[field]) == 1
        key = record[field][0].lower()
        assert key
        identity = (kind, key)
        assert identity not in seen
        seen.add(identity)
        if "Preferred-Value" not in record and kind not in ("extlang", "grandfathered"):
            continue
        preferred = record.get("Preferred-Value", [""])
        assert len(preferred) == 1
        preferred = preferred[0].lower()
        assert "Preferred-Value" not in record or preferred
        prefix = ""
        if kind == "extlang":
            assert re.fullmatch(r"[a-z]{3}", key) and preferred
            assert len(record["Prefix"]) == 1
            prefix = record["Prefix"][0].lower()
            assert re.fullmatch(r"[a-z]{2,3}", prefix)
        for value in (key, preferred):
            assert not value or (len(value) <= 64 and re.fullmatch(
                r"[a-z0-9]{1,8}(?:-[a-z0-9]{1,8})*", value))
        identity = (kinds[kind], key)
        assert identity not in records
        records[identity] = (preferred, prefix)
    assert records
    pool = bytearray(b"\0")
    offsets = {"": 0}

    def intern(value):
        if value not in offsets:
            offsets[value] = len(pool)
            pool.extend(value.encode("ascii") + b"\0")
        return offsets[value]

    rows = []
    for (kind, key), (preferred, prefix) in sorted(records.items()):
        rows.append((intern(key), intern(preferred), intern(prefix), kind))
    assert len(pool) < 65536
    lines = ["/* Generated by gen_vtt_languages.py from the IANA Language Subtag Registry.",
             " * https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry",
             " * " + date,
             " * SHA-256: " + hashlib.sha256(raw).hexdigest() + " */",
             "#ifndef LIBRETRO_RSUBTITLE_LANGUAGES_H",
             "#define LIBRETRO_RSUBTITLE_LANGUAGES_H", "", "#include <stdint.h>", "",
             "struct vtt_language_alias", "{", "   uint16_t key, preferred, extlang_prefix;",
             "   uint8_t kind;", "};", "",
             "static const char vtt_language_strings[] =", "{"]
    for start in range(0, len(pool), 16):
        lines.append("   " + ", ".join(str(v) for v in pool[start:start + 16]) + ",")
    lines.extend(["};", "", "static const struct vtt_language_alias vtt_language_aliases[] =", "{"])
    lines.extend("   {%u, %u, %u, %u}," % row for row in rows)
    lines.extend(["};", "", "#endif", ""])
    return "\n".join(lines).encode("ascii"), len(rows), len(pool)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    output, count, size = generate(args.source.read_bytes())
    if args.verify:
        if args.output.read_bytes().replace(b"\r\n", b"\n") != output:
            raise SystemExit("language table differs from the supplied IANA snapshot")
    else:
        args.output.write_bytes(output)
    print("%u aliases, %u string bytes, no pointer relocations" % (count, size))


if __name__ == "__main__":
    main()
