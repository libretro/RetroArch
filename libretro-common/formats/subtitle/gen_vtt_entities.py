#!/usr/bin/env python3
"""Generate the WebVTT character-reference table from WHATWG entities.json."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("source", type=Path)
parser.add_argument("output", type=Path)
parser.add_argument("--verify", action="store_true")
args = parser.parse_args()
raw = args.source.read_bytes()
data = json.loads(raw)
names = bytearray()
rows = []
for key in sorted(data):
    assert key.startswith("&") and len(key) > 1
    name = key[1:].encode("ascii")
    assert len(name) <= 32 and all(chr(c).isalnum() or c == 59 for c in name)
    points = data[key]["codepoints"]
    assert 1 <= len(points) <= 2
    assert all(0 < p <= 0x10ffff and not 0xd800 <= p <= 0xdfff for p in points)
    rows.append((points[0], points[1] if len(points) == 2 else 0, len(names)))
    names.extend(name + b"\0")
assert len(names) < 65536
lines = ["/* Generated by gen_vtt_entities.py from WHATWG entities.json.",
         " * https://html.spec.whatwg.org/entities.json",
         " * SHA-256: " + hashlib.sha256(raw).hexdigest() + " */",
         "#ifndef LIBRETRO_RSUBTITLE_ENTITIES_H", "#define LIBRETRO_RSUBTITLE_ENTITIES_H", "",
         "#include <stdint.h>", "", "struct vtt_entity", "{",
         "   uint32_t first, second;", "   uint16_t name;", "};", "",
         "static const char vtt_entity_names[] =", "{"]
for start in range(0, len(names), 16):
    lines.append("   " + ", ".join(str(v) for v in names[start:start + 16]) + ",")
lines.extend(["};", "", "static const struct vtt_entity vtt_entities[] =", "{"])
lines.extend("   {0x%x, 0x%x, %u}," % row for row in rows)
lines.extend(["};", "", "#endif", ""])
output = "\n".join(lines).encode("ascii")
if args.verify:
    if args.output.read_bytes().replace(b"\r\n", b"\n") != output:
        raise SystemExit("entity table differs from the supplied WHATWG snapshot")
else:
    args.output.write_bytes(output)
print("%u entities, %u name bytes, no pointer relocations" % (len(rows), len(names)))
