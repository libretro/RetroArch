"""Generate rmpeg4_tables.h: the variable length code tables of ISO/IEC
14496-2 Annex B, with H.263's that the short video header uses.

The code words are read from a pinned FFmpeg revision's table files as a
transcription of the standard's tables, nothing else: download the two
SOURCES, then pass the directory holding them. No network access is
performed by this tool. Every table is checked to be prefix-free and, where
the standard fixes it, to hold the expected entries. --check compares the
generated header without writing it.

usage: gen_tables.py [--check] DIR rmpeg4_tables.h
"""
import hashlib
import re
import sys

REV = '08d6ed2100b26c0161cab08570b3fbe70de0f765'
SOURCES = {
    'h263data.c':  '0c763621cefd3fd5e7c9d8315df58bb8a58c5c17686282cca7332e71d410003d',
    'mpeg4data.h': '8aaddec4f13c3f1e90fd92b233a38c049b1072223809c90f51c5d5e8c60a33ad',
}
URL = 'https://raw.githubusercontent.com/FFmpeg/FFmpeg/' + REV + '/libavcodec/'

args = sys.argv[1:]
check = bool(args) and args[0] == '--check'
if check:
    args = args[1:]
if len(args) != 2:
    raise SystemExit(__doc__)
src, dest = args
text = ''
for name, digest in SOURCES.items():
    data = open(src + '/' + name, 'rb').read()
    if hashlib.sha256(data).hexdigest() != digest:
        raise SystemExit('%s is not %s%s' % (name, URL, name))
    text += data.decode('utf-8')


def array(name):
    m = re.search(r'\b' + re.escape(name) + r'\s*\[[^=]*=\s*\{(.*?)\};', text, re.S)
    if not m:
        raise SystemExit('missing ' + name)
    body = re.sub(r'//[^\n]*', '', m.group(1))
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return [int(x, 0) for x in re.findall(r'-?(?:0x[0-9a-fA-F]+|\d+)', body)]


def pairs(name):
    a = array(name)
    return [(a[i], a[i + 1]) for i in range(0, len(a), 2)]


def check_prefix_free(name, codes):
    words = [format(c, '0%db' % l) for c, l in codes if l]
    for i, a in enumerate(words):
        for j, b in enumerate(words):
            if i != j and b.startswith(a):
                raise SystemExit('%s: %s is a prefix of %s' % (name, a, b))


out = []
w = out.append

w('/* Generated by gen_tables.py from the variable length code tables of')
w(' * ISO/IEC 14496-2 Annex B and ITU-T H.263 Annex C (short video header).')
w(' * Do not edit. Every table is prefix-free; the generator checks it. */')
w('')
w('#ifndef __LIBRETRO_SDK_FORMAT_RMPEG4_TABLES_H')
w('#define __LIBRETRO_SDK_FORMAT_RMPEG4_TABLES_H')
w('')
w('#include <stdint.h>')
w('')
w('/* A code. a is the symbol (its index unless noted); for the coefficient')
w(' * tables a, b, c are last, run and level, level 0 being the escape. */')
w('typedef struct')
w('{')
w('   uint16_t code;')
w('   uint8_t  len;')
w('   uint8_t  a;')
w('   uint8_t  b;')
w('   uint8_t  c;')
w('} rmpeg4_vlc_t;')
w('')


def simple(cname, codes, values=None, comment=''):
    check_prefix_free(cname, codes)
    if comment:
        w('/* %s */' % comment)
    w('static const rmpeg4_vlc_t %s[] = {' % cname)
    n = 0
    for i, (c, l) in enumerate(codes):
        if not l:
            continue
        v = i if values is None else values[i]
        w('   { 0x%04X, %2d, %3d, 0, 0 },   /* %s */' % (c, l, v, format(c, '0%db' % l)))
        n += 1
    w('   { 0, 0, 0, 0, 0 }')
    w('};')
    w('')
    return n


mc_intra = list(zip(array('ff_h263_intra_MCBPC_code'), array('ff_h263_intra_MCBPC_bits')))
assert len(mc_intra) == 9
simple('rmpeg4_vlc_mcbpc_intra', mc_intra, comment=
       'MCBPC for I-VOPs, Table B-6: value = (mb_type 3 or 4) - 3 << 2 | cbpc; 8 is stuffing')
mc_inter = list(zip(array('ff_h263_inter_MCBPC_code'), array('ff_h263_inter_MCBPC_bits')))
assert len(mc_inter) == 28
simple('rmpeg4_vlc_mcbpc_inter', mc_inter, comment=
       'MCBPC for P- and S-VOPs, Table B-7: value = mb_type << 2 | cbpc, mb_type\n'
       ' * 0 inter, 1 intra, 2 inter+q, 3 intra+q, 4 inter4v, 6 inter4v+q; 20 is stuffing')
cbpy = pairs('ff_h263_cbpy_tab')
assert len(cbpy) == 16
simple('rmpeg4_vlc_cbpy', cbpy, comment='CBPY, Table B-8: value = cbpy of an intra macroblock')
mv = pairs('ff_mvtab')
assert len(mv) == 33
simple('rmpeg4_vlc_mvd', mv, comment='motion_code magnitude, Table B-12 (a sign bit follows a non-zero one)')
dcl = pairs('ff_mpeg4_DCtab_lum')
dcc = pairs('ff_mpeg4_DCtab_chrom')
assert len(dcl) == 13 and len(dcc) == 13
simple('rmpeg4_vlc_dc_lum', [(c, l) for c, l in dcl], comment='dct_dc_size_luminance, Table B-13')
simple('rmpeg4_vlc_dc_chr', [(c, l) for c, l in dcc], comment='dct_dc_size_chrominance, Table B-14')
mbb = pairs('ff_mb_type_b_tab')
simple('rmpeg4_vlc_mb_type_b', mbb, comment=
       'mb_type in B-VOPs, Table B-4: 0 direct, 1 interpolate, 2 backward, 3 forward')

# dmv_length of sprite trajectories, Table B-33: canonical codes from lengths
lens = array('ff_sprite_trajectory_lens')
assert len(lens) == 15
codes, code, prev = [], 0, lens[0]
for i, l in enumerate(lens):
    if i:
        code = (code + 1) << (l - prev)
    codes.append((code, l))
    prev = l
# The standard's table: 00, 010 .. 110, 1110, 11110, ... 111111111110
assert codes[0] == (0, 2) and codes[1] == (2, 3) and codes[6] == (0xE, 4) and codes[14] == (0xFFE, 12)
simple('rmpeg4_vlc_sprite_dmv', codes, comment='dmv_length of a sprite trajectory, Table B-33')


def tcoef(cname, vlc, run, level, last_from, comment):
    pairs_ = [(vlc[i], vlc[i + 1]) for i in range(0, len(vlc), 2)]
    n = len(run)
    assert len(pairs_) == n + 1 and len(level) == n
    check_prefix_free(cname, pairs_)
    w('/* %s */' % comment)
    w('static const rmpeg4_vlc_t %s[] = {' % cname)
    maxl = [[0] * 64 for _ in range(2)]
    maxr = [[0] * 64 for _ in range(2)]
    for i, (c, l) in enumerate(pairs_):
        if i == n:
            w('   { 0x%04X, %2d, 0,  0,  0 },   /* %s escape */' % (c, l, format(c, '0%db' % l)))
            continue
        last = 1 if i >= last_from else 0
        w('   { 0x%04X, %2d, %d, %2d, %2d },   /* %s */' % (c, l, last, run[i], level[i], format(c, '0%db' % l)))
        maxl[last][run[i]] = max(maxl[last][run[i]], level[i])
        maxr[last][level[i]] = max(maxr[last][level[i]], run[i] + 1)
    w('   { 0, 0, 0, 0, 0 }')
    w('};')
    w('')
    return maxl, maxr


def lmax_rmax(prefix, maxl, maxr):
    # LMAX: the largest level a code carries for a run; RMAX: one more
    # than the largest run for a level (the escape modes add these)
    for t, name in ((maxl, 'lmax'), (maxr, 'rmax')):
        w('static const uint8_t %s_%s[2][64] = {' % (prefix, name))
        for last in range(2):
            row = ', '.join('%2d' % v for v in t[last])
            w('   { %s },' % row)
        w('};')
        w('')


ml, mr = tcoef('rmpeg4_tcoef_intra', array('ff_mpeg4_intra_vlc'), array('ff_mpeg4_intra_run'),
               array('ff_mpeg4_intra_level'), 67,
               'TCOEF of intra blocks, Table B-16 (a sign bit follows)')
lmax_rmax('rmpeg4_intra', ml, mr)
ml, mr = tcoef('rmpeg4_tcoef_inter', array('ff_inter_vlc'), array('ff_inter_run'),
               array('ff_inter_level'), 58,
               'TCOEF of inter blocks, Table B-17, also H.263\'s (a sign bit follows)')
lmax_rmax('rmpeg4_inter', ml, mr)
tcoef('rmpeg4_rvlc_intra', array('intra_rvlc'), array('intra_rvlc_run'),
      array('intra_rvlc_level'), 103,
      'Reversible TCOEF of intra blocks, Table B-23 (a sign bit follows)')
tcoef('rmpeg4_rvlc_inter', array('inter_rvlc'), array('inter_rvlc_run'),
      array('inter_rvlc_level'), 103,
      'Reversible TCOEF of inter blocks, Table B-23 (a sign bit follows)')

for name in ('ff_mpeg4_default_intra_matrix', 'ff_mpeg4_default_non_intra_matrix'):
    m = array(name)
    assert len(m) == 64
    cname = 'rmpeg4_default_intra' if 'intra_matrix' in name and 'non' not in name else 'rmpeg4_default_inter'
    w('/* Default %s quantiser matrix, Table 7-3 / 7-4, raster order */' % ('intra' if 'non' not in name else 'non-intra'))
    w('static const uint8_t %s[64] = {' % cname)
    for r in range(8):
        w('   ' + ', '.join('%2d' % v for v in m[r * 8:r * 8 + 8]) + ',')
    w('};')
    w('')

for name, cname in (('ff_mpeg4_y_dc_scale_table', 'rmpeg4_dc_scale_lum'),
                    ('ff_mpeg4_c_dc_scale_table', 'rmpeg4_dc_scale_chr')):
    m = array(name)
    assert len(m) == 32
    w('/* dc_scaler by quantiser_scale, Table 7-1 */')
    w('static const uint8_t %s[32] = {' % cname)
    w('   ' + ', '.join(str(v) for v in m))
    w('};')
    w('')

thr = array('ff_mpeg4_dc_threshold')
assert thr == [99, 13, 15, 17, 19, 21, 23, 0]
w('/* intra_dc_vlc_thr: the quantiser below which DC has its own code, Table 6-21 */')
w('static const uint8_t rmpeg4_dc_threshold[8] = { %s };' % ', '.join(map(str, thr)))
w('')
w('#endif')
result = '\n'.join(out) + '\n'
if check:
    if open(dest).read() != result:
        raise SystemExit(dest + ' differs from what the tables generate')
else:
    open(dest, 'w').write(result)
