struct state
{
   uint32_t slots[2][CELLS], saved[2][CELLS];
   unsigned w, h, shown;
   const uint32_t *held[2];
   int mode;
   retro_atomic_int_t copies;
};
static int start(void *user, unsigned w, unsigned h, unsigned count)
{
   struct state *s = (struct state*)user;
   CHECK(w == s->w && h == s->h && count == 2);
   return VIDEO_PLAYER_RGBA | VIDEO_PLAYER_BORROW_PIXELS;
}
static uint32_t *begin(void *user, unsigned slot)
{ CHECK(slot < 2); return ((struct state*)user)->slots[slot] + 1; }
static unsigned stride(void *user, unsigned slot)
{ (void)user; CHECK(slot < 2); return STRIDE; }
static enum video_player_present present(void *user, const video_player_frame_t *fr)
{
   struct state *s = (struct state*)user;
   const uint32_t *pixels;
   unsigned y;
   CHECK(fr->slot < 2 && !fr->planar);
   pixels = fr->pixels ? fr->pixels : s->slots[fr->slot] + 1;
   s->held[fr->slot] = pixels;
   CHECK(s->mode == 2 ? fr->pixels != NULL : fr->pixels == NULL);
   for (y = 0; y < s->h; y++)
      memcpy(s->saved[fr->slot] + 1 + y * STRIDE,
            pixels + y * (fr->pixels ? s->w : STRIDE), s->w * sizeof(uint32_t));
   s->shown++;
   return VIDEO_PLAYER_PRESENT_QUEUED;
}
static void decoded(void *user, enum video_player_how how)
{
   if (how == VIDEO_PLAYER_COPY || how == VIDEO_PLAYER_SWIZZLE)
      retro_atomic_fetch_add_int(&((struct state*)user)->copies, 1);
}
static void worker(const unsigned char *blob, size_t len, int mode)
{
   struct state s;
   video_player_sink_t sink;
   rwebp_anim_stream_t *stream = rwebp_anim_stream_open(blob, len);
   video_player_t *p;
   unsigned i, x, y;
   memset(&s, 0, sizeof(s)); memset(&sink, 0, sizeof(sink));
   memset(s.slots, 0x55, sizeof(s.slots)); s.mode = mode;
   CHECK(stream); rwebp_anim_stream_get_info(stream, &s.w, &s.h, NULL, NULL);
   sink.user = &s; sink.start = start; sink.slot_begin = begin;
   sink.slot_stride = stride; sink.present = present; sink.decoded = decoded;
   p = video_player_new(stream, IMAGE_TYPE_WEBP, 1, &sink, 0); CHECK(p);
   for (i = 0; i < 2000 && s.shown < 2; i++)
   {
      CHECK(video_player_poll(p, (int64_t)i * 10000) == VIDEO_PLAYER_PLAYING);
      retro_sleep(1);
   }
   CHECK(s.shown == 2);
   CHECK(mode ? retro_atomic_load_acquire_int(&s.copies) == 0
              : retro_atomic_load_acquire_int(&s.copies) >= 2);
   for (i = 0; i < 2; i++)
   {
      for (y = 0; y < s.h; y++)
      {
         CHECK(!memcmp(s.held[i] + y * (mode == 2 ? s.w : STRIDE),
               s.saved[i] + 1 + y * STRIDE, s.w * sizeof(uint32_t)));
         for (x = s.w; x < STRIDE; x++) CHECK(s.slots[i][1 + y * STRIDE + x] == 0x55555555u);
      }
      CHECK(s.slots[i][0] == 0x55555555u);
      for (x = 1 + s.h * STRIDE; x < CELLS; x++) CHECK(s.slots[i][x] == 0x55555555u);
      if (mode == 2)
         for (x = 0; x < CELLS; x++) CHECK(s.slots[i][x] == 0x55555555u);
      video_player_slot_released(p, i);
   }
   for (i = 0; i < 2000 && !video_player_stop(p); i++) retro_sleep(1);
   CHECK(i < 2000);
   video_player_free(p); rwebp_anim_stream_close(stream);
   video_player_worker_deinit();
}
