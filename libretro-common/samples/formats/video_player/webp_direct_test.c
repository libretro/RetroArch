#define STRIDE 8
#define CELLS 66
static void direct(const unsigned char *blob, size_t len, int argb)
{
   rwebp_anim_stream_t *s = rwebp_anim_stream_open(blob, len);
   rwebp_anim_stream_t *ref = rwebp_anim_stream_open(blob, len);
   uint32_t slots[2][CELLS], saved[CELLS];
   const uint32_t *a, *b;
   void *owner;
   unsigned w, h, i, x, y;
   int da, db;
   CHECK(s && ref);
   rwebp_anim_stream_get_info(s, &w, &h, NULL, NULL);
   CHECK(w == 5 && h <= 7);
   rwebp_anim_stream_set_argb(s, argb); rwebp_anim_stream_set_argb(ref, argb);
   CHECK(rwebp_anim_stream_next(s, &da)); /* retain a stale private canvas */
   rwebp_anim_stream_rewind(s);
   memset(slots, 0x55, sizeof(slots));
   for (i = 0; i < 3; i++)
   {
      unsigned slot = i & 1;
      if (i == 1)
      {
         rwebp_anim_stream_set_argb(s, !argb);
         rwebp_anim_stream_set_argb(ref, !argb);
      }
      CHECK(rwebp_anim_stream_set_output_stride(s, slots[slot] + 1, STRIDE));
      CHECK(!rwebp_anim_stream_set_output_stride(s, slots[slot ^ 1] + 1, w - 1));
      a = rwebp_anim_stream_next(s, &da); b = rwebp_anim_stream_next(ref, &db);
      CHECK(a == slots[slot] + 1 && b && da == 50 && da == db);
      CHECK(!rwebp_anim_stream_take_pixels(s));
      for (y = 0; y < h; y++)
      {
         CHECK(!memcmp(a + y * STRIDE, b + y * w, w * sizeof(uint32_t)));
         for (x = w; x < STRIDE; x++) CHECK(a[y * STRIDE + x] == 0x55555555u);
      }
      CHECK(slots[slot][0] == 0x55555555u);
      for (x = 1 + h * STRIDE; x < CELLS; x++) CHECK(slots[slot][x] == 0x55555555u);
      if (!i) memcpy(saved, slots[0], sizeof(saved));
      if (i == 1) CHECK(!memcmp(saved, slots[0], sizeof(saved)));
   }
   CHECK(rwebp_anim_stream_set_output_stride(s, NULL, 0));
   CHECK(!rwebp_anim_stream_take_pixels(s)); /* last output was still a lend */
   rwebp_anim_stream_rewind(s); rwebp_anim_stream_rewind(ref);
   a = rwebp_anim_stream_next(s, &da); b = rwebp_anim_stream_next(ref, &db);
   CHECK(a && b && !memcmp(a, b, w * h * sizeof(uint32_t)));
   owner = rwebp_anim_stream_take_pixels(s); CHECK(owner == a);
   memcpy(saved, slots[0], sizeof(saved));
   rwebp_anim_stream_close(s); rwebp_anim_stream_close(ref); free(owner);
   CHECK(!memcmp(saved, slots[0], sizeof(saved)));
}
static void fallback(const unsigned char *blob, size_t len, int retained)
{
   rwebp_anim_stream_t *s = rwebp_anim_stream_open(blob, len);
   uint32_t out[CELLS];
   const uint32_t *pixels;
   void *owner;
   int duration;
   CHECK(s && !rwebp_anim_stream_set_output_stride(s, out, STRIDE));
   pixels = rwebp_anim_stream_next(s, &duration); CHECK(pixels);
   owner = rwebp_anim_stream_take_pixels(s);
   CHECK(retained ? owner == pixels : owner == NULL);
   rwebp_anim_stream_close(s); free(owner);
}
static unsigned read32(const unsigned char *p)
{ return p[0] | ((unsigned)p[1] << 8) | ((unsigned)p[2] << 16) | ((unsigned)p[3] << 24); }
static void resumable(void)
{
   rvp8_dec *s = (rvp8_dec*)calloc(1, sizeof(*s));
   uint32_t packed[35], padded[7 * STRIDE];
   size_t at;
   int cursor = 0;
   unsigned x, y;
   CHECK(s);
   for (at = 12; at + 18 < sizeof(odd) && memcmp(odd + at, "VP8 ", 4); at++) ;
   CHECK(at + 18 < sizeof(odd));
   CHECK(rvp8_begin(odd + at + 8, read32(odd + at + 4), s) == 0);
   while (rvp8_rows(s, s->mbh) > 0) ;
   rvp8_filter_rows(s, 0, s->mbh);
   CHECK(s->w == 5 && s->h == 7);
   memset(padded, 0x55, sizeof(padded));
   CHECK(rvp8_upsample_rows_stride(s, padded, 4, 0, 1) == -1);
   for (x = 0; x < 7 * STRIDE; x++) CHECK(padded[x] == 0x55555555u);
   CHECK(rvp8_upsample_rows(s, packed, 0, s->h) == s->h);
   while (cursor < s->h)
   {
      int next = rvp8_upsample_rows_stride(s, padded, STRIDE, cursor, 1);
      CHECK(next > cursor); cursor = next;
   }
   for (y = 0; y < 7; y++)
   {
      CHECK(!memcmp(padded + y * STRIDE, packed + y * 5, 5 * sizeof(uint32_t)));
      for (x = 5; x < STRIDE; x++) CHECK(padded[y * STRIDE + x] == 0x55555555u);
   }
   rvp8_abort(s); free(s);
}
