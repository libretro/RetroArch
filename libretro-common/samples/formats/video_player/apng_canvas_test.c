static void direct(const unsigned char *blob, size_t len, int argb)
{
   rpng_apng_stream_t *s = rpng_apng_stream_open(blob, len);
   rpng_apng_stream_t *ref = rpng_apng_stream_open(blob, len);
   uint32_t slots[2][34], saved[34];
   const uint32_t *a, *b;
   unsigned i, x, y;
   int da, db;
   CHECK(s && ref && rpng_apng_stream_set_argb(s, argb)
         && rpng_apng_stream_set_argb(ref, argb));
   memset(slots, 0x55, sizeof(slots));
   for (i = 0; i < 3; i++)
   {
      unsigned slot = i & 1;
      if (i == 1)
      {
         CHECK(rpng_apng_stream_set_argb(s, !argb));
         CHECK(rpng_apng_stream_set_argb(ref, !argb));
      }
      CHECK(rpng_apng_stream_set_output_stride(s, slots[slot] + 1, 8));
      CHECK(!rpng_apng_stream_set_output_stride(s, slots[slot ^ 1] + 1, 3));
      a = rpng_apng_stream_next(s, &da); b = rpng_apng_stream_next(ref, &db);
      CHECK(a == slots[slot] + 1 && b && da == 50 && da == db);
      for (y = 0; y < 4; y++)
      {
         CHECK(!memcmp(a + y * 8, b + y * 4, 4 * sizeof(uint32_t)));
         for (x = 4; x < 8; x++) CHECK(a[y * 8 + x] == 0x55555555u);
      }
      CHECK(slots[slot][0] == 0x55555555u && slots[slot][33] == 0x55555555u);
      if (!i) memcpy(saved, slots[0], sizeof(saved));
      if (i == 1) CHECK(!memcmp(saved, slots[0], sizeof(saved)));
   }
   rpng_apng_stream_rewind(s); rpng_apng_stream_rewind(ref);
   CHECK(rpng_apng_stream_set_output_stride(s, NULL, 0));
   a = rpng_apng_stream_next(s, &da); b = rpng_apng_stream_next(ref, &db);
   CHECK(a && b && a != slots[0] + 1 && !memcmp(a, b, 16 * sizeof(uint32_t)));
   memcpy(saved, slots[0], sizeof(saved));
   rpng_apng_stream_close(s); rpng_apng_stream_close(ref);
   CHECK(!memcmp(saved, slots[0], sizeof(saved)));
}
static void fallback(const unsigned char *blob, size_t len)
{
   uint32_t out[32];
   rpng_apng_stream_t *s = rpng_apng_stream_open(blob, len);
   int duration, i;
   CHECK(s && !rpng_apng_stream_set_output_stride(s, out, 8));
   for (i = 0; i < 3; i++) CHECK(rpng_apng_stream_next(s, &duration));
   rpng_apng_stream_close(s);
}
static void progressive(void)
{
   uint32_t out[32];
   int need, duration;
   rpng_apng_stream_t *s = rpng_apng_stream_open_avail(rgba,
         sizeof(rgba), sizeof(rgba) - 12, &need);
   CHECK(s && !rpng_apng_stream_set_output_stride(s, out, 8));
   rpng_apng_stream_set_avail(s, sizeof(rgba));
   CHECK(rpng_apng_stream_set_output_stride(s, out, 8));
   CHECK(rpng_apng_stream_next(s, &duration) == out);
   rpng_apng_stream_close(s);
}
