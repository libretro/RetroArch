static int failures = 0;
static int checks   = 0;

static void check(int ok, const char *what)
{
   checks++;
   printf("  %-5s %s\n", ok ? "ok" : "FAIL", what);
   if (!ok)
      failures++;
}

typedef struct
{
   const uint8_t *data;
   size_t         len;
   unsigned       reads;
} source_t;

static int64_t read_cb(void *ud, uint64_t off, void *dst, size_t len)
{
   source_t *s = (source_t*)ud;
   if (off > s->len)
      return -1;
   if (len > s->len - (size_t)off)
      len = s->len - (size_t)off;
   memcpy(dst, s->data + (size_t)off, len);
   s->reads++;
   return (int64_t)len;
}

static void check_member(rzip_archive_t *a, const char *name,
      const uint8_t *want, size_t want_len, int in_memory, const char *what)
{
   int            idx = rzip_archive_find(a, name);
   const uint8_t *view;
   uint8_t       *out = NULL;
   size_t         len = 0;
   char           label[96];

   strcpy(label, what);
   strcat(label, ": ");
   strcat(label, name);

   check(idx >= 0, label);
   if (idx < 0)
      return;
   check(rzip_archive_entry(a, (uint32_t)idx)->size == want_len, label);

   view = rzip_archive_entry_view(a, (uint32_t)idx, &len);
   if (in_memory && rzip_archive_entry(a, (uint32_t)idx)->method == RZIP_METHOD_STORED)
      check(view && len == want_len && !memcmp(view, want, want_len), label);
   else
      check(view == NULL, label);

   check(rzip_archive_extract(a, (uint32_t)idx, &out, &len) == RZIP_OK
         && len == want_len && !memcmp(out, want, want_len), label);
   free(out);
}

static void check_archive(const uint8_t *data, size_t len, const char *what,
      const char *b_name, const uint8_t *a_want, const uint8_t *b_want)
{
   rzip_archive_t *a = NULL;
   source_t        src;
   int             res;

   printf("%s\n", what);

   res = rzip_archive_open(&a, data, len, NULL, NULL);
   check(res == RZIP_OK && a, "open in memory");
   if (a)
   {
      check_member(a, "a.bin", a_want, A_LEN, 1, "memory");
      if (b_name)
         check_member(a, b_name, b_want, B_LEN, 1, "memory");
      check(rzip_archive_find(a, "dir/") < 0, "a directory is not a member");
      check(rzip_archive_find(a, "nope.bin") < 0, "a missing name");
      rzip_archive_close(a);
   }

   src.data  = data;
   src.len   = len;
   src.reads = 0;
   a         = NULL;
   res       = rzip_archive_open(&a, NULL, len, read_cb, &src);
   check(res == RZIP_OK && a, "open through reads");
   if (a)
   {
      check_member(a, "a.bin", a_want, A_LEN, 0, "reads");
      if (b_name)
         check_member(a, b_name, b_want, B_LEN, 0, "reads");
      rzip_archive_close(a);
   }
}

int main(void)
{
   static uint8_t a_want[A_LEN];
   static uint8_t b_want[B_LEN];
   rzip_archive_t *a = NULL;
   uint32_t        i;

   for (i = 0; i < A_LEN; i++)
      a_want[i] = (uint8_t)((i * 2654435761u) >> 13);
   for (i = 0; i < B_LEN; i++)
      b_want[i] = (uint8_t)((i * 7) % 251);

   check_archive(stored_zip, sizeof(stored_zip), "stored, extra fields, subdirectory",
         "dir/b.bin", a_want, b_want);
   check_archive(deflated_zip, sizeof(deflated_zip), "deflated",
         "b.bin", a_want, b_want);
   check_archive(zip64_zip, sizeof(zip64_zip), "zip64 records",
         NULL, a_want, b_want);
   check_archive(commented_zip, sizeof(commented_zip), "archive comment",
         NULL, a_want, b_want);

   /* not an archive, and one cut short of its directory */
   check(rzip_archive_open(&a, a_want, A_LEN, NULL, NULL) != RZIP_OK && !a,
         "random bytes are refused");
   check(rzip_archive_open(&a, stored_zip, sizeof(stored_zip) - 30, NULL, NULL) != RZIP_OK && !a,
         "a truncated archive is refused");

   printf("%d checks, %d failures\n", checks, failures);
   return failures ? 1 : 0;
}
