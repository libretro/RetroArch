#define FRAMES 12
#define SPLIT  6

static int fails;

#define CHECK(cond, what) \
   do { if (!(cond)) { printf("FAIL: %s\n", what); fails++; } } while (0)

/* decode frames [first, last) of the stream, appending to out */
static size_t decode(raac_t *dec, unsigned first, unsigned last, int16_t *out)
{
   size_t   pos = 0, n = 0;
   unsigned f   = 0;
   while (pos + 7 <= sizeof(stream) && f < last)
   {
      raac_adts_t h;
      if (raac_adts_parse(stream + pos, sizeof(stream) - pos, &h) < 0)
         break;
      if (f >= first)
      {
         int got = raac_decode_s16(dec, stream + pos + h.header_size,
               h.frame_size - h.header_size, out + n * 2);
         if (got > 0)
            n += (size_t)got;
      }
      pos += h.frame_size;
      f++;
   }
   return n;
}

int main(void)
{
   static int16_t a[FRAMES * RAAC_MAX_FRAME * 2];
   static int16_t b[FRAMES * RAAC_MAX_FRAME * 2];
   raac_adts_t h;
   raac_t     *dec, *dec2;
   size_t      n, n1, n2, i, from;
   double      sll = 0, srr = 0, slr = 0;
   void       *state;

   if (raac_adts_parse(stream, sizeof(stream), &h) < 0
         || !(dec = raac_open(h.asc, sizeof(h.asc))))
   {
      printf("raac_ps_test: FAIL (open)\n");
      return 1;
   }
   CHECK(raac_channels(dec) == 2, "mono HE-AAC decodes to two channels");
   CHECK(raac_frame_len(dec) == 2048, "SBR frame length");

   n = decode(dec, 0, FRAMES, a);
   CHECK(n == FRAMES * 2048, "every frame decodes");

   /* the second half: the two tones, not one signal twice */
   from = n / 2;
   for (i = from; i < n; i++)
   {
      double l = a[i * 2], r = a[i * 2 + 1];
      sll += l * l;
      srr += r * r;
      slr += l * r;
   }
   CHECK(sll > 1e6 && srr > 1e6, "both channels carry sound");
   CHECK(fabs(slr) < 0.5 * sqrt(sll * srr), "left and right differ");

   raac_reset(dec);
   CHECK(decode(dec, 0, FRAMES, b) == n && !memcmp(a, b, n * 4),
         "the same again after raac_reset");

   raac_reset(dec);
   n1    = decode(dec, 0, SPLIT, b);
   state = malloc(raac_state_size(dec));
   raac_save_state(dec, state);
   dec2  = raac_open(h.asc, sizeof(h.asc));
   CHECK(dec2 && raac_load_state(dec2, state, raac_state_size(dec)) == 0,
         "savestate loads");
   n2 = dec2 ? decode(dec2, SPLIT, FRAMES, b + n1 * 2) : 0;
   CHECK(n1 + n2 == n && !memcmp(a, b, n * 4),
         "the same from a savestate taken partway");

   free(state);
   raac_close(dec2);
   raac_close(dec);
   printf("raac_ps_test: %s (%d failures)\n", fails ? "FAIL" : "PASS", fails);
   return fails ? 1 : 0;
}
