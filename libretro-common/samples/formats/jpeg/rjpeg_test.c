/* rjpeg regression tests.
 *
 * Each case here corresponds to a defect that was actually observed, so
 * that the specific shape of the bug cannot come back unnoticed:
 *
 *   prefix_matches_whole
 *     The entropy bit buffer reads ahead of the decode position.  When a
 *     resident frontier is in play the read-ahead must not cross it, or
 *     the decoder consumes bytes that have not arrived and commits an MCU
 *     row from them.  Feeding the same image in every chunk size must
 *     therefore produce exactly the whole-buffer output.
 *
 *   bad_dc_category_baseline / bad_dc_category_progressive
 *     A DC magnitude category comes straight out of a Huffman table and
 *     is used both as a shift count and as an index into the bmask/bias
 *     tables.  A corrupt DHT can make it arbitrary, so it has to be range
 *     checked; unchecked it reads those tables out of bounds and shifts
 *     by more than the bit-buffer width.  Both streams below carry a DHT
 *     whose first DC symbol is 0x40.  They must be rejected, not decoded,
 *     and must not fault.  Run this file under ASan/UBSan to get the full
 *     value: without the range check both cases trip them.
 *
 *   truncation_never_faults
 *     Every truncation of a valid stream must either decode or fail
 *     cleanly.  A truncated stream has no single correct output, so this
 *     asserts termination and memory safety only, not pixels.
 *
 *   sync_matches_iterative
 *     The monolithic and the iterative drivers must agree bit for bit.
 *
 * Build and run:  make && ./rjpeg_test
 */

