static int failures;

static void check(int cond, const char *what)
{
   if (!cond)
   {
      printf("  FAIL  %s\n", what);
      failures++;
   }
}

static uint64_t fnv(const unsigned char *p, size_t n)
{
   uint64_t h = 1469598103934665603ULL;
   size_t   i;
   for (i = 0; i < n; i++)
      h = (h ^ p[i]) * 1099511628211ULL;
   return h;
}

/* Decode the whole buffer at once.  use_iterate selects the driver.
 * Returns the output checksum, or 0 with *ok cleared. */
static uint64_t decode_whole(const unsigned char *jpg, size_t len,
      int use_iterate, unsigned *w, unsigned *h, int *ok)
{
   rjpeg_t  *r    = rjpeg_alloc();
   uint32_t *data = NULL;
   uint64_t  sum  = 0;
   int       ret  = IMAGE_PROCESS_ERROR;

   *ok = 0;
   if (!r)
      return 0;
   if (rjpeg_set_buf_ptr(r, (void*)jpg, len))
   {
      if (use_iterate)
      {
         rjpeg_set_out_rgba(r, true);
         if (rjpeg_start(r))
            while (rjpeg_iterate_image(r)) { }
      }
      do
      {
         ret = rjpeg_process_image(r, (void**)&data, len, w, h, true);
      } while (ret == IMAGE_PROCESS_NEXT);
   }

   if (ret == IMAGE_PROCESS_END && data)
   {
      sum = fnv((const unsigned char*)data, (size_t)*w * (size_t)*h * 4);
      *ok = 1;
   }
   free(data);
   rjpeg_free(r);
   return sum;
}

/* Decode while revealing the buffer chunk bytes at a time, the way a
 * caller streaming a file off disk would. */
static uint64_t decode_prefix(const unsigned char *jpg, size_t len,
      size_t chunk, unsigned *w, unsigned *h, int *ok)
{
   rjpeg_t  *r     = rjpeg_alloc();
   uint32_t *data  = NULL;
   uint64_t  sum   = 0;
   size_t    avail = chunk < len ? chunk : len;
   int       ret   = IMAGE_PROCESS_ERROR;

   *ok = 0;
   if (!r)
      return 0;
   if (!rjpeg_set_buf_ptr(r, (void*)jpg, len))
   {
      rjpeg_free(r);
      return 0;
   }
   rjpeg_set_out_rgba(r, true);
   rjpeg_set_avail(r, avail);

   /* The header must be resident before the decode can start. */
   while (!rjpeg_header_ready(jpg, avail) && avail < len)
   {
      avail += chunk;
      if (avail > len)
         avail = len;
      rjpeg_set_avail(r, avail);
   }

   if (rjpeg_start(r))
   {
      for (;;)
      {
         while (rjpeg_iterate_image(r)) { }
         if (!rjpeg_need_more(r) || avail >= len)
            break;
         avail += chunk;
         if (avail > len)
            avail = len;
         rjpeg_set_avail(r, avail);
      }
      do
      {
         ret = rjpeg_process_image(r, (void**)&data, len, w, h, true);
      } while (ret == IMAGE_PROCESS_NEXT);
   }

   if (ret == IMAGE_PROCESS_END && data)
   {
      sum = fnv((const unsigned char*)data, (size_t)*w * (size_t)*h * 4);
      *ok = 1;
   }
   free(data);
   rjpeg_free(r);
   return sum;
}

static void test_sync_matches_iterative(void)
{
   unsigned w = 0, h = 0, w2 = 0, h2 = 0;
   int      ok = 0, ok2 = 0;
   uint64_t a  = decode_whole(rjpeg_valid, sizeof(rjpeg_valid), 0, &w,  &h,  &ok);
   uint64_t b  = decode_whole(rjpeg_valid, sizeof(rjpeg_valid), 1, &w2, &h2, &ok2);

   printf("sync_matches_iterative\n");
   check(ok && ok2,               "both drivers decode the reference image");
   check(w == 24 && h == 17,      "synchronous geometry is 24x17");
   check(w2 == 24 && h2 == 17,    "iterative geometry is 24x17");
   check(a == b,                  "synchronous and iterative agree bit for bit");
}

static void test_prefix_matches_whole(void)
{
   static const size_t chunks[] =
      { 1, 2, 3, 5, 7, 11, 16, 32, 64, 128, 256, 997, 4096, 65536 };
   unsigned w = 0, h = 0;
   int      ok = 0;
   uint64_t ref = decode_whole(rjpeg_valid, sizeof(rjpeg_valid), 1, &w, &h, &ok);
   size_t   i;

   printf("prefix_matches_whole\n");
   check(ok, "reference decode succeeds");

   for (i = 0; i < sizeof(chunks) / sizeof(chunks[0]); i++)
   {
      unsigned pw = 0, ph = 0;
      int      pok = 0;
      uint64_t got = decode_prefix(rjpeg_valid, sizeof(rjpeg_valid),
            chunks[i], &pw, &ph, &pok);
      char     msg[96];

      sprintf(msg, "chunk size %u reproduces the whole-buffer output",
            (unsigned)chunks[i]);
      check(pok && got == ref && pw == w && ph == h, msg);
   }
}

static void test_bad_dc_category(const unsigned char *jpg, size_t len,
      const char *label)
{
   unsigned w = 0, h = 0;
   int      ok = 0;
   int      m;

   printf("%s\n", label);
   for (m = 0; m <= 1; m++)
   {
      /* The point is that this returns at all, and reports failure
       * rather than handing back a decoded image built from an
       * out-of-range magnitude category. */
      decode_whole(jpg, len, m, &w, &h, &ok);
      check(!ok, m ? "iterative driver rejects the stream"
                   : "synchronous driver rejects the stream");
   }
}

static void test_truncation_never_faults(void)
{
   size_t len = sizeof(rjpeg_valid);
   size_t cut;
   int    decoded = 0, rejected = 0;

   printf("truncation_never_faults\n");
   for (cut = 1; cut < len; cut++)
   {
      unsigned w = 0, h = 0;
      int      ok = 0;
      decode_whole(rjpeg_valid, cut, 1, &w, &h, &ok);
      if (ok)
         decoded++;
      else
         rejected++;
   }
   check(decoded + rejected == (int)len - 1,
         "every truncation length terminates");
   printf("        (%d decoded, %d rejected of %d lengths)\n",
         decoded, rejected, (int)len - 1);
}

int main(void)
{
   test_sync_matches_iterative();
   test_prefix_matches_whole();
   test_bad_dc_category(rjpeg_bad_dc_baseline,
         sizeof(rjpeg_bad_dc_baseline), "bad_dc_category_baseline");
   test_bad_dc_category(rjpeg_bad_dc_progressive,
         sizeof(rjpeg_bad_dc_progressive), "bad_dc_category_progressive");
   test_truncation_never_faults();

   if (failures)
      printf("\n%d check(s) failed\n", failures);
   else
      printf("\nall checks passed\n");
   return failures ? 1 : 0;
}
