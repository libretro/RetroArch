#!/usr/bin/env python3
"""Generate immutable default tone/output tables; no runtime shared writes."""
from pathlib import Path
import argparse
import math
import re
import struct

p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
args = p.parse_args()
root = Path(__file__).resolve().parents[3]
source = (root / 'formats/image/image_hdr_blit.c').read_text()
scene = source.split('static const float image_hdr_hlg_scene[1024] =', 1)[1].split('};', 1)[0]
scene = [struct.unpack('f', struct.pack('f', float(v)))[0]
         for v in re.findall(r'([0-9.eE+\-]+)f', scene)]
assert len(scene) == 1024

def hable(x):
    return ((x * (.15 * x + .05) + .004) / (x * (.15 * x + .50) + .06)) - .02 / .30

peak = 1000.0 / 203.0
lo, hi = 1.0, 8.0
for _ in range(48):
    gain = (lo + hi) * .5
    if hable(gain) / hable(gain * peak) < .8:
        lo = gain
    else:
        hi = gain
pq, hlg = [], []
for i in range(1024):
    ep = math.pow(i / 1023.0, 1.0 / 78.84375)
    light = math.pow(max(0.0, ep - .8359375) / (18.8515625 - 18.6875 * ep), 1.0 / .1593017578125)
    pq.append(int(min(1.0, hable(gain * (10000.0 * light / 203.0)) / hable(gain * peak)) * 65535.0 + .5))
    light = 1000.0 * math.pow(scene[i], 1.2) / 203.0
    hlg.append(int(min(1.0, hable(gain * light) / hable(gain * peak)) * 65535.0 + .5))
out8, out10 = [], []
for i in range(8193):
    light = i / 8192.0
    encoded = 12.92 * light if light <= .0031308 else 1.055 * math.pow(light, 1.0 / 2.4) - .055
    out8.append(int(encoded * 255.0 + .5))
    out10.append(int(encoded * 1023.0 + .5))

text = '/* Generated by samples/formats/image_hdr_blit/generate_tone_tables.py.\n * SPDX-License-Identifier: MIT\n */\n'
for name, kind, values in [('image_hdr_pq_default', 'uint16_t', pq),
                            ('image_hdr_hlg_default', 'uint16_t', hlg),
                            ('image_hdr_out8', 'uint8_t', out8),
                            ('image_hdr_out10', 'uint16_t', out10)]:
    text += '\nstatic const %s %s[%d] =\n{\n' % (kind, name, len(values))
    text += '\n'.join('   ' + ', '.join(map(str, values[i:i+16])) + ',' for i in range(0, len(values), 16))
    text += '\n};\n'
target = root / 'formats/image/image_hdr_tone_lut.h'
if args.check:
    assert target.read_text() == text, 'generated HDR tone tables are stale'
else:
    target.write_text(text)
print('HDR immutable tables:', len(pq) + len(hlg) + len(out8) + len(out10), 'entries')
