static int failures = 0;
static int checks   = 0;

static void check(int ok, const char *what)
{
   checks++;
   printf("  %-5s %s\n", ok ? "ok" : "FAIL", what);
   if (!ok)
      failures++;
}

static void fill_a(uint8_t *a)
{
   uint32_t i;
   for (i = 0; i < A_LEN; i++)
      a[i] = (uint8_t)((i * 2654435761u) >> 13);
}

static void fill_b(uint8_t *b)
{
   uint32_t i;
   for (i = 0; i < B_LEN; i++)
      b[i] = (uint8_t)((i * 7) % 251);
}

/* Member @index of @a must come back as @want, through detach and then
 * through a plain extract. */
static void check_member(r7z_archive_t *a, uint32_t index, const char *name,
      const uint8_t *want, size_t want_len, int detach_first)
{
   uint8_t *out = NULL;
   size_t   out_len = 0;
   int      res;

   if (detach_first)
   {
      res = r7z_archive_extract_detach(a, index, &out, &out_len);
      check(res == R7Z_OK && out_len == want_len
            && !memcmp(out, want, want_len), name);
      free(out);
      out = NULL;
   }

   res = r7z_archive_extract(a, index, &out, &out_len);
   check(res == R7Z_OK && out_len == want_len
         && !memcmp(out, want, want_len), name);
   free(out);
}

static void check_archive(const uint8_t *data, size_t len, const char *what,
      const uint8_t *a_want, const uint8_t *b_want)
{
   r7z_archive_t *a = NULL;
   int            res = r7z_archive_open(&a, data, len);

   printf("%s\n", what);
   check(res == R7Z_OK && a && r7z_archive_num_entries(a) == 2, "open");
   if (res != R7Z_OK || !a)
      return;

   /* detach, then extract the same member again: the buffer that was
    * handed over must not be the one the next extract reads */
   check_member(a, 0, "a.bin: detach, extract", a_want, A_LEN, 1);
   check_member(a, 1, "b.bin: detach, extract", b_want, B_LEN, 1);
   /* and the other way round, so a stale cache from the detach of one
    * member cannot serve the next */
   check_member(a, 1, "b.bin: extract", b_want, B_LEN, 0);
   check_member(a, 0, "a.bin: detach, extract", a_want, A_LEN, 1);
   check_member(a, 1, "b.bin: detach, extract", b_want, B_LEN, 1);

   r7z_archive_close(a);
}

int main(void)
{
   static uint8_t a_want[A_LEN];
   static uint8_t b_want[B_LEN];

   fill_a(a_want);
   fill_b(b_want);

   check_archive(nonsolid_7z, sizeof(nonsolid_7z),
         "non-solid: each member is its own folder", a_want, b_want);
   check_archive(solid_7z, sizeof(solid_7z),
         "solid: both members in one folder", a_want, b_want);

   printf("%d checks, %d failures\n", checks, failures);
   return failures ? 1 : 0;
}
