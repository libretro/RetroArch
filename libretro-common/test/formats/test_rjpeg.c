/* Regression coverage for the rjpeg fused iterate+resample and its
 * plane ring.
 *
 * Two properties, each guarding a class of past defect:
 *
 * 1. PATH EQUIVALENCE.  The fused iterative path (rjpeg_start /
 *    rjpeg_iterate_image, then rjpeg_process_image) must produce
 *    byte-identical output to the synchronous path (process_image
 *    alone), which decodes whole-image with full planes and no
 *    fusion.  This is the structural reference: the MCU-row seam
 *    corruption (fused emission without the one-row lag), the stale
 *    byte-order latch, and the grayscale monolithic-fallback ring
 *    overflow all manifested as the two paths disagreeing.  Checked
 *    for both byte orders across 4:2:0, 4:4:4, grayscale, restart-
 *    interval and progressive streams.
 *
 * 2. ABANDONED-DECODE TEARDOWN.  A cancelled thumbnail task can call
 *    rjpeg_free at any machine state.  Abandon a fresh context after
 *    every possible number of iterate calls and after every possible
 *    number of process calls, then assert a subsequent full decode
 *    still matches the reference.  The runtime assertion catches
 *    state leakage; the memory assertions belong to the sanitizer
 *    this suite is expected to also run under (ASan or valgrind),
 *    which turns any interior free, double free, leak or overflow in
 *    the teardown or ring paths into a hard failure.
 *
 * The streams are tiny (24x17) pre-encoded JPEGs embedded below, one
 * per coding shape, so the suite needs no encoder and no files. */

