#!/usr/bin/env python3
"""Write libretro-common/net/cacert.h: the CA bundle as C arrays small
enough for every compiler that builds it.

MSVC before Visual Studio 2019 refuses a string literal longer than
65535 bytes after concatenation (fatal error C1091), and the Mozilla
bundle is several times that. So the bundle is kept as several arrays,
each well under the limit and each ending where a certificate does,
listed in cacert_pem_parts[] / cacert_pem_sizes[]: the TLS client loads
every part into one trust store, no copy made.

Usage:
  cacert_split.py <cacert.pem | cacert.h> [out.h]

Reads the bundle from a PEM file (curl's cacert.pem from
https://curl.se/docs/caextract.html) or from an existing cacert.h, so
the header can be regenerated from itself; writes the header to out.h,
or to stdout.
"""

import re
import sys

# Well under MSVC's 65535, with room for the per-line bytes it counts
PART_LIMIT = 60000

END = "-----END CERTIFICATE-----\n"


def bundle_from_header(text):
    """The bundle text a cacert.h spells: its string literals, in order,
    joined."""
    out = []
    for lit in re.findall(r'"((?:[^"\\]|\\.)*)"', text):
        out.append(bytes(lit, "latin-1").decode("unicode_escape"))
    return "".join(out)


def split(bundle):
    """The bundle cut after certificate ends into parts no longer than
    PART_LIMIT (with the NUL each array carries)."""
    pieces, pos = [], 0
    while True:
        i = bundle.find(END, pos)
        if i < 0:
            break
        pieces.append(bundle[pos:i + len(END)])
        pos = i + len(END)
    if pos < len(bundle):
        pieces.append(bundle[pos:])
    parts, cur = [], ""
    for p in pieces:
        if len(p) + 1 > PART_LIMIT:
            raise SystemExit("a single certificate is larger than a part")
        if cur and len(cur) + len(p) + 1 > PART_LIMIT:
            parts.append(cur)
            cur = ""
        cur += p
    if cur:
        parts.append(cur)
    return parts


def c_lines(text):
    out = []
    for line in text.splitlines(True):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        out.append('"%s"' % esc)
    return out


def emit(parts):
    o = []
    o.append("/* CA certificates extracted from Mozilla")
    o.append(" * https://curl.haxx.se/docs/caextract.html")
    o.append(" * NOTE: Newlines are necessary for the file to be parsed correctly!")
    o.append(" *")
    o.append(" * Generated by tools/cacert_split.py, which also regenerates it: the")
    o.append(" * bundle is split where certificates end into parts under 64 KiB,")
    o.append(" * since MSVC before 2019 refuses a longer string literal (C1091).")
    o.append(" * Every part is NUL-terminated PEM; load them all.")
    o.append(" */")
    for i, part in enumerate(parts):
        o.append("static const char cacert_pem_%d[] = {" % i)
        o.extend(c_lines(part))
        o.append("};")
    o.append("")
    o.append("#define CACERT_PEM_PARTS %d" % len(parts))
    o.append("static const char *const cacert_pem_parts[CACERT_PEM_PARTS] = {")
    o.append(",\n".join("   cacert_pem_%d" % i for i in range(len(parts))))
    o.append("};")
    o.append("static const size_t cacert_pem_sizes[CACERT_PEM_PARTS] = {")
    o.append(",\n".join("   sizeof(cacert_pem_%d)" % i for i in range(len(parts))))
    o.append("};")
    return "\n".join(o) + "\n"


def main():
    src = open(sys.argv[1], encoding="latin-1").read()
    bundle = src if "-----BEGIN CERTIFICATE-----" in src and "static const char" not in src \
        else bundle_from_header(src)
    out = emit(split(bundle))
    if len(sys.argv) > 2:
        open(sys.argv[2], "w", encoding="latin-1", newline="\n").write(out)
    else:
        sys.stdout.write(out)


if __name__ == "__main__":
    main()
