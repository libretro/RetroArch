#!/usr/bin/env python3
"""RGUI 8-bit -> 16bpp pixel format conversion contract check.

RGUI renders into a 16bpp framebuffer, so every menu colour, wallpaper
and thumbnail pixel goes through one of the argb32_to_* converters in
menu/drivers/rgui.c.  Each converter quantises the four 8-bit input
channels to the widths of its target format and then ORs them into
their fields.  The widths and the shifts are written out by hand, on
separate lines, once per format - and there are fourteen driver idents
mapping onto seven formats, plus a dithered twin of each.

Nothing checks that a channel's quantised width still fits the shift
it is packed at.  When it does not, the OR silently spills the top of
one channel into the bottom of its neighbour: no warning, no overflow,
just wrong colours.  Worse, the formats are per-platform, so the
damage lands on whichever platform owns that converter and on no
other.  A desktop build stays perfect.

This actually shipped.  c6b66c9 widened green in argb32_to_rgb565 from
5 bits to 6, correctly, but left the packing at `(g << 6)` where a
6-bit green needs `(g << 5)`.  Green's top bit landed on red's LSB and
the green field became (g & 31) << 1, so green wrapped hard at half
scale - mid grey came out (139, 0, 131) - on sdl_dingux, sdl_rs90 and
xvideo.  It reached users as #19469, bisected by hand on an Anbernic
RG300X, because no machine in CI runs a 565 menu.

So, per driver ident in rgui_pixel_format_map, and for the fallback:

1. The bits each input channel can change must be disjoint from every
   other channel's.  This is the c6b66c9 failure, stated generally.
2. Each channel's bits must be contiguous.
3. Endpoints must be exact: input 0 gives an all-zero field, input
   255 an all-ones field.
4. Field value must be monotonic in the input - the visible symptom
   of a spill is a channel that falls as its input rises.
5. The dithered twin must reach exactly the same bits as the plain
   converter, and land within one level of it.  Equal reach is also
   what catches a table row wired to the wrong format's twin.

The converters are static inside a 9000-line file, so the marked
`pixel format conversion` block is lifted out and compiled on its own
against two stubs.  That keeps the test on the real shipped code -
including the real dispatch table - rather than on a copy that can
drift.  Nothing is hardcoded about any format's layout; the field
masks are measured from the converters themselves.

Usage:
   tools/rgui_pixfmt_check.py [--selftest] [--root DIR] [--cc CC]

Exit status is 0 when every converter honours the contract, 1
otherwise.
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

RGUI_C = os.path.join("menu", "drivers", "rgui.c")

MARK_START = "pixel format conversion START"
MARK_END = "pixel format conversion END"

# `(r << 11) | (g << N) | b` - the packing line c6b66c9 got wrong.
# Used only to build selftest fixtures, never to judge the tree.
RE_565_PACK = re.compile(
    r"(return\s*\(r\s*<<\s*11\)\s*\|\s*\(g\s*<<\s*)(\d+)(\)\s*\|\s*b;)")


def extract_block(root):
    """Return the marked pixel-format region of rgui.c as C source."""
    path = os.path.join(root, RGUI_C)
    with open(path, "r") as handle:
        lines = handle.readlines()

    start = end = None
    for i, line in enumerate(lines):
        if MARK_START in line:
            start = i
        elif MARK_END in line:
            end = i
            break

    if start is None or end is None or end <= start:
        raise SystemExit(
            "%s: could not find the '%s' / '%s' banner comments.\n"
            "The checker lifts the converters out by those markers; if "
            "they were renamed, update MARK_START/MARK_END here too."
            % (path, MARK_START, MARK_END))

    # The markers sit on the middle line of a three-line banner, so
    # step over the banner's closing (and opening) rule.
    return "".join(lines[start + 2:end - 1])


HARNESS = r"""
/* Generated by tools/rgui_pixfmt_check.py - do not edit. */
#include <stdio.h>
#include <string.h>
#include <stdint.h>
#include <boolean.h>
#include <retro_inline.h>

#define ARRAY_SIZE(a) (sizeof(a) / sizeof((a)[0]))

static const char *g_ident = "";

static const char *video_driver_get_ident(void)
{
   return g_ident;
}

static bool string_is_equal(const char *a, const char *b)
{
   return strcmp(a, b) == 0;
}

/* ---- lifted verbatim from menu/drivers/rgui.c ---- */
@@BLOCK@@
/* ---- end lifted region ---- */

typedef uint16_t (*conv_t)(uint32_t);
typedef uint16_t (*convd_t)(uint32_t, unsigned, unsigned);

static const char *g_chan[4] = { "alpha", "red", "green", "blue" };
static const unsigned g_shift[4] = { 24, 16, 8, 0 };

static int g_failures = 0;

/* Build a test colour that varies only channel `ch`.
 *
 * The RGB sweeps hold alpha opaque so the formats that premultiply
 * (1555, 565, 5A3) are not also being swept through their alpha
 * fade.  The alpha sweep holds RGB at zero, which stays zero under
 * premultiplication - so whatever moves is alpha's own field, if it
 * has one, and nothing else. */
static uint32_t test_colour(int ch, unsigned v)
{
   if (ch == 0)
      return (uint32_t)v << 24;
   return (uint32_t)0xFF000000u | ((uint32_t)v << g_shift[ch]);
}

/* Bits that CHANGE as one channel sweeps its full range.  Bits that
 * are merely set - a forced alpha bit, a pinned neighbour - are held
 * constant and correctly do not count as this channel's. */
static uint16_t reach_plain(conv_t f, int ch)
{
   uint16_t base = 0;
   uint16_t acc  = 0;
   unsigned v;

   for (v = 0; v < 256; v++)
   {
      uint16_t o = f(test_colour(ch, v));
      if (v == 0)
         base = o;
      acc |= (uint16_t)(o ^ base);
   }
   return acc;
}

static uint16_t reach_dither(convd_t f, int ch)
{
   uint16_t base = 0;
   uint16_t acc  = 0;
   unsigned v, x, y;

   for (v = 0; v < 256; v++)
      for (y = 0; y < 4; y++)
         for (x = 0; x < 4; x++)
         {
            uint16_t o = f(test_colour(ch, v), x, y);
            if (v == 0 && x == 0 && y == 0)
               base = o;
            acc |= (uint16_t)(o ^ base);
         }
   return acc;
}

static unsigned first_bit(uint16_t mask)
{
   unsigned i;
   for (i = 0; i < 16; i++)
      if (mask & (1u << i))
         return i;
   return 0;
}

static int is_contiguous(uint16_t mask)
{
   /* A contiguous run, shifted down, is one less than a power of two. */
   uint16_t m = (uint16_t)(mask >> first_bit(mask));
   return (m & (uint16_t)(m + 1)) == 0;
}

static unsigned field_of(uint16_t pixel, uint16_t mask)
{
   return (unsigned)((pixel & mask) >> first_bit(mask));
}

static void report(const char *ident, const char *msg)
{
   printf("[fail] %-11s %s\n", ident, msg);
   g_failures++;
}

static void check_ident(const char *ident)
{
   char buf[256];
   conv_t  plain;
   convd_t dith;
   uint16_t rp[4], rd[4];
   int ch, other;

   int before = g_failures;

   g_ident = ident;
   (void)rgui_set_pixel_format_function();
   plain = argb32_to_pixel_platform_format;
   dith  = argb32_to_pixel_platform_format_dither;

   for (ch = 0; ch < 4; ch++)
   {
      rp[ch] = reach_plain(plain, ch);
      rd[ch] = reach_dither(dith, ch);
   }

   /* 1. Channels must not share bits. */
   for (ch = 0; ch < 4; ch++)
      for (other = ch + 1; other < 4; other++)
      {
         uint16_t overlap = (uint16_t)(rp[ch] & rp[other]);
         if (overlap)
         {
            sprintf(buf,
               "%s and %s share bits %04x (%s=%04x %s=%04x) - a "
               "quantised width does not match its packing shift",
               g_chan[ch], g_chan[other], overlap,
               g_chan[ch], rp[ch], g_chan[other], rp[other]);
            report(ident, buf);
         }
      }

   for (ch = 0; ch < 4; ch++)
   {
      uint16_t mask = rp[ch];
      unsigned full, v, x, y, prev;

      /* A channel with no field of its own (alpha under 565) is
       * legitimately absent; nothing further to check. */
      if (!mask)
      {
         if (rd[ch])
         {
            sprintf(buf, "%s is absent from the plain converter but "
               "reaches %04x in the dithered one", g_chan[ch], rd[ch]);
            report(ident, buf);
         }
         continue;
      }

      /* 2. Contiguity. */
      if (!is_contiguous(mask))
      {
         sprintf(buf, "%s occupies discontiguous bits %04x",
            g_chan[ch], mask);
         report(ident, buf);
         continue;
      }

      /* 5a. The dithered twin must cover the same field exactly. */
      if (rd[ch] != mask)
      {
         sprintf(buf, "%s reaches %04x plain but %04x dithered - "
            "mismatched converter pair, or the dither spills",
            g_chan[ch], mask, rd[ch]);
         report(ident, buf);
      }

      full = (unsigned)(mask >> first_bit(mask));

      /* 3. Endpoints exact. */
      if (field_of(plain(test_colour(ch, 0)), mask) != 0)
      {
         sprintf(buf, "%s: input 0 does not give an empty field",
            g_chan[ch]);
         report(ident, buf);
      }
      if (field_of(plain(test_colour(ch, 255)), mask) != full)
      {
         sprintf(buf, "%s: input 255 gives %u, not full scale %u",
            g_chan[ch],
            field_of(plain(test_colour(ch, 255)), mask), full);
         report(ident, buf);
      }

      /* 4. Monotonic in the input. */
      prev = 0;
      for (v = 0; v < 256; v++)
      {
         unsigned cur = field_of(plain(test_colour(ch, v)), mask);
         if (cur < prev)
         {
            sprintf(buf, "%s: field falls from %u to %u at input %u "
               "- the channel is wrapping", g_chan[ch], prev, cur, v);
            report(ident, buf);
            break;
         }
         prev = cur;
      }

      for (y = 0; y < 4; y++)
         for (x = 0; x < 4; x++)
         {
            prev = 0;
            for (v = 0; v < 256; v++)
            {
               unsigned cur =
                  field_of(dith(test_colour(ch, v), x, y), mask);
               if (cur < prev)
               {
                  sprintf(buf, "%s: dithered field falls from %u to "
                     "%u at input %u, cell (%u,%u)",
                     g_chan[ch], prev, cur, v, x, y);
                  report(ident, buf);
                  v = 256;
                  x = 4;
                  y = 4;
                  break;
               }
               prev = cur;
            }
         }

      /* 5b. Dither may only nudge a level, never restate it. */
      for (v = 0; v < 256; v++)
      {
         unsigned p = field_of(plain(test_colour(ch, v)), mask);
         for (y = 0; y < 4; y++)
            for (x = 0; x < 4; x++)
            {
               unsigned d =
                  field_of(dith(test_colour(ch, v), x, y), mask);
               unsigned diff = (d > p) ? (d - p) : (p - d);
               if (diff > 1)
               {
                  sprintf(buf, "%s: dithered field %u differs from "
                     "plain %u by %u levels at input %u",
                     g_chan[ch], d, p, diff, v);
                  report(ident, buf);
                  v = 256;
                  x = 4;
                  y = 4;
               }
            }
      }
   }

   if (g_failures == before)
   {
      printf("[ok]   %-11s", ident);
      for (ch = 0; ch < 4; ch++)
         printf(" %s=%04x", g_chan[ch], rp[ch]);
      printf("\n");
   }
}

int main(void)
{
   size_t i;

   for (i = 0; i < ARRAY_SIZE(rgui_pixel_format_map); i++)
      check_ident(rgui_pixel_format_map[i].driver_ident);

   /* The fallback path: an ident no row matches. */
   check_ident("no_such_video_driver");

   if (g_failures)
   {
      printf("\n%d contract violation(s).\n", g_failures);
      return 1;
   }
   printf("\nAll converters honour the contract.\n");
   return 0;
}
"""


def run_block(block, root, cc, keep=False):
    """Compile the harness around `block` and run it.

    Returns (exit_status, combined_output)."""
    tmp = tempfile.mkdtemp(prefix="rgui_pixfmt_")
    src = os.path.join(tmp, "rgui_pixfmt_harness.c")
    exe = os.path.join(tmp, "rgui_pixfmt_harness")

    with open(src, "w") as handle:
        handle.write(HARNESS.replace("@@BLOCK@@", block))

    cmd = [cc, "-std=c89", "-pedantic", "-Wall",
           "-I" + os.path.join(root, "libretro-common", "include"),
           "-I" + root, src, "-o", exe]

    build = subprocess.run(cmd, stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT, universal_newlines=True)
    if build.returncode != 0:
        return 1, ("harness failed to compile - the lifted region may "
                   "have gained a dependency that needs a stub:\n"
                   + build.stdout)

    run = subprocess.run([exe], stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, universal_newlines=True)
    if not keep:
        for path in (src, exe):
            if os.path.exists(path):
                os.remove(path)
        os.rmdir(tmp)
    return run.returncode, run.stdout


def _repack_565(block, shift):
    """Return `block` with the RGB565 green packing forced to `shift`."""
    return RE_565_PACK.sub(
        lambda m: "%s%d%s" % (m.group(1), shift, m.group(3)), block)


def selftest(root, cc):
    """Prove the checker separates the c6b66c9 regression from its fix.

    Both fixtures are derived from the tree by forcing the green
    packing shift either way, so the selftest says the same thing
    whether or not the tree is currently fixed."""
    block = extract_block(root)

    if not RE_565_PACK.search(block):
        print("[fail] selftest: could not find the RGB565 packing line; "
              "the fixture generator needs updating")
        return 1

    failures = 0

    good = _repack_565(block, 5)
    status, out = run_block(good, root, cc)
    if status == 0:
        print("[ok]   fixture: 6-bit green packed at <<5 passes")
    else:
        print("[fail] fixture: the corrected converter should pass:\n" + out)
        failures += 1

    bad = _repack_565(block, 6)
    status, out = run_block(bad, root, cc)
    if status != 0 and "share bits" in out:
        print("[ok]   fixture: c6b66c9's 6-bit green at <<6 is caught")
    else:
        print("[fail] fixture: the #19469 regression went undetected:\n" + out)
        failures += 1

    # A table row pointing at another format's dithered twin.
    mixed = block.replace("argb32_to_rgb565,   argb32_to_rgb565_dither",
                          "argb32_to_rgb565,   argb32_to_abgr4444_dither", 1)
    if mixed == block:
        print("[fail] selftest: could not build the mismatched-pair "
              "fixture; the dispatch table's formatting changed")
        failures += 1
    else:
        status, out = run_block(mixed, root, cc)
        if status != 0:
            print("[ok]   fixture: a mismatched conv/conv_dither pair "
                  "is caught")
        else:
            print("[fail] fixture: mismatched converter pair went "
                  "undetected:\n" + out)
            failures += 1

    if failures:
        print("\nSelftest failed: the checker is not trustworthy.")
        return 1
    print("\nSelftest passed.")
    return 0


def main():
    parser = argparse.ArgumentParser(
        description="Check RGUI's 8-bit -> 16bpp converters.")
    parser.add_argument("--selftest", action="store_true",
                        help="run the fixtures instead of the tree")
    parser.add_argument("--root", default=".",
                        help="RetroArch source root (default: .)")
    parser.add_argument("--cc", default=os.environ.get("CC", "cc"),
                        help="C compiler to build the harness with")
    args = parser.parse_args()

    if args.selftest:
        return selftest(args.root, args.cc)

    status, out = run_block(extract_block(args.root), args.root, args.cc)
    sys.stdout.write(out)
    if status != 0:
        print("\nSee tools/rgui_pixfmt_check.py for what these mean.")
    return status


if __name__ == "__main__":
    sys.exit(main())
