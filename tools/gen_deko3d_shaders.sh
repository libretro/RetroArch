#!/bin/sh
# Regenerates gfx/drivers/deko3d_shaders/menu_dksh.h from the menu
# shaders' GLSL with devkitPro's uam: the DKSH blobs as C arrays, which
# the deko3d and Switch drivers embed, so neither needs uam to build.
# Run from the tree root after changing the GLSL, and commit the header.
set -eu

UAM="${DEVKITPRO:-/opt/devkitpro}/tools/bin/uam"
DIR=gfx/drivers/deko3d_shaders
OUT="$DIR/menu_dksh.h"
TMP="${TMPDIR:-/tmp}/gen_deko3d_shaders.$$"

if [ ! -x "$UAM" ] && [ ! -x "$UAM.exe" ]; then
   echo "gen_deko3d_shaders: no uam at $UAM (set DEVKITPRO)" >&2
   exit 1
fi
mkdir -p "$TMP"
trap 'rm -rf "$TMP"' EXIT

"$UAM" -s vert -o "$TMP/vsh.dksh" "$DIR/deko3d_menu_vsh.glsl"
"$UAM" -s frag -o "$TMP/fsh.dksh" "$DIR/deko3d_menu_fsh.glsl"

# One array: name, then the bytes, sixteen to a line
emit() {
   name=$1
   file=$2
   size=$(wc -c < "$file" | tr -d ' ')
   echo "static const uint8_t ${name}[${size}] = {"
   od -An -v -tx1 "$file" | awk '
      { for (i = 1; i <= NF; i++) { b[n++] = "0x" $i } }
      END {
         for (i = 0; i < n; i++) {
            if (i % 16 == 0) printf "   "
            printf "%s%s", b[i], (i + 1 < n) ? "," : ""
            if (i % 16 == 15 || i + 1 == n) printf "\n"; else printf " "
         }
      }'
   echo "};"
}

{
   echo "/* Generated by tools/gen_deko3d_shaders.sh from"
   echo " * deko3d_menu_vsh.glsl and deko3d_menu_fsh.glsl with uam: the menu"
   echo " * pipeline's shaders as DKSH (control section, then code). Do not"
   echo " * edit; change the GLSL and run the script again. */"
   echo "#ifndef DEKO3D_MENU_DKSH_H__"
   echo "#define DEKO3D_MENU_DKSH_H__"
   echo ""
   echo "#include <stdint.h>"
   echo ""
   emit deko3d_menu_vsh_dksh "$TMP/vsh.dksh"
   echo ""
   emit deko3d_menu_fsh_dksh "$TMP/fsh.dksh"
   echo ""
   echo "#endif"
} > "$OUT"

echo "wrote $OUT"
