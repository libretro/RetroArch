#!/bin/sh
# Regenerates gfx/drivers/deko3d_shaders/menu_dksh.h from the menu
# shaders' GLSL with devkitPro's uam: the DKSH blobs as C arrays, which
# the deko3d and Switch drivers embed, so neither needs uam to build.
# And menu_effects_dksh.h: the menu effects (ribbon, snow, bokeh,
# snowflake) from the Vulkan driver's GLSL, the one source of them, as
# uam takes it - no descriptor set, the ribbon's header pasted in - with
# pipeline_quad.vert for the effects drawn over the screen's quad.
# Run from the tree root after changing the GLSL, and commit the headers.
set -eu

UAM="${DEVKITPRO:-/opt/devkitpro}/tools/bin/uam"
DIR=gfx/drivers/deko3d_shaders
OUT="$DIR/menu_dksh.h"
FX_OUT="$DIR/menu_effects_dksh.h"
VK=gfx/drivers/vulkan_shaders
TMP="${TMPDIR:-/tmp}/gen_deko3d_shaders.$$"

if [ ! -x "$UAM" ] && [ ! -x "$UAM.exe" ]; then
   echo "gen_deko3d_shaders: no uam at $UAM (set DEVKITPRO)" >&2
   exit 1
fi
mkdir -p "$TMP"
trap 'rm -rf "$TMP"' EXIT

"$UAM" -s vert -o "$TMP/vsh.dksh" "$DIR/deko3d_menu_vsh.glsl"
"$UAM" -s frag -o "$TMP/fsh.dksh" "$DIR/deko3d_menu_fsh.glsl"

# A Vulkan effect shader as uam takes it
fx() {
   stage=$1
   src=$2
   name=$3
   sed -e 's/set = 0, //' -e '/GL_GOOGLE_include_directive/d' \
       -e '/#include "..\/menu_ribbon_shader.h"/{
r gfx/drivers/menu_ribbon_shader.h
d
}' "$src" > "$TMP/$name.glsl"
   "$UAM" -s "$stage" -o "$TMP/$name.dksh" "$TMP/$name.glsl"
}

"$UAM" -s vert -o "$TMP/fx_quad_vert.dksh" "$DIR/pipeline_quad.vert"
fx vert "$VK/pipeline_ribbon.vert"        fx_ribbon_vert
fx frag "$VK/pipeline_ribbon.frag"        fx_ribbon_frag
fx vert "$VK/pipeline_ribbon_simple.vert" fx_ribbon_simple_vert
fx frag "$VK/pipeline_ribbon_simple.frag" fx_ribbon_simple_frag
fx frag "$VK/pipeline_snow_simple.frag"   fx_snow_simple_frag
fx frag "$VK/pipeline_snow.frag"          fx_snow_frag
fx frag "$VK/pipeline_bokeh.frag"         fx_bokeh_frag
fx frag "$VK/pipeline_snowflake.frag"     fx_snowflake_frag

# One array: name, then the bytes, sixteen to a line
emit() {
   name=$1
   file=$2
   size=$(wc -c < "$file" | tr -d ' ')
   echo "static const uint8_t ${name}[${size}] = {"
   od -An -v -tx1 "$file" | awk '
      { for (i = 1; i <= NF; i++) { b[n++] = "0x" $i } }
      END {
         for (i = 0; i < n; i++) {
            if (i % 16 == 0) printf "   "
            printf "%s%s", b[i], (i + 1 < n) ? "," : ""
            if (i % 16 == 15 || i + 1 == n) printf "\n"; else printf " "
         }
      }'
   echo "};"
}

{
   echo "/* Generated by tools/gen_deko3d_shaders.sh from"
   echo " * deko3d_menu_vsh.glsl and deko3d_menu_fsh.glsl with uam: the menu"
   echo " * pipeline's shaders as DKSH (control section, then code). Do not"
   echo " * edit; change the GLSL and run the script again. */"
   echo "#ifndef DEKO3D_MENU_DKSH_H__"
   echo "#define DEKO3D_MENU_DKSH_H__"
   echo ""
   echo "#include <stdint.h>"
   echo ""
   emit deko3d_menu_vsh_dksh "$TMP/vsh.dksh"
   echo ""
   emit deko3d_menu_fsh_dksh "$TMP/fsh.dksh"
   echo ""
   echo "#endif"
} > "$OUT"

{
   echo "/* Generated by tools/gen_deko3d_shaders.sh from the Vulkan driver's"
   echo " * menu effect shaders and deko3d_shaders/pipeline_quad.vert with uam:"
   echo " * DKSH (control section, then code). Do not edit; change the GLSL"
   echo " * and run the script again. */"
   echo "#ifndef DEKO3D_MENU_EFFECTS_DKSH_H__"
   echo "#define DEKO3D_MENU_EFFECTS_DKSH_H__"
   echo ""
   echo "#include <stdint.h>"
   for n in fx_quad_vert fx_ribbon_vert fx_ribbon_frag fx_ribbon_simple_vert \
            fx_ribbon_simple_frag fx_snow_simple_frag fx_snow_frag \
            fx_bokeh_frag fx_snowflake_frag; do
      echo ""
      emit "deko3d_${n}_dksh" "$TMP/$n.dksh"
   done
   echo ""
   echo "#endif"
} > "$FX_OUT"

echo "wrote $OUT and $FX_OUT"
