"""Generate DXBC on Windows, or check source/blob digests on any platform."""
from pathlib import Path
import ctypes
import hashlib
import re
import sys

root = Path(__file__).resolve().parent
source = (root / 'capture_rgb.hlsl').read_bytes().replace(b'\r\n', b'\n')
output = root / 'capture_rgb.h'
digest = hashlib.sha256(source).hexdigest()
if sys.argv[1:] == ['--check']:
    header = output.read_text(encoding='utf-8')
    assert 'Source SHA256: ' + digest in header
    for name in ('vs', 'ps'):
        body = re.search(r'rgc_' + name + r'\[\] = \{(.*?)\};', header, re.S).group(1)
        blob = bytes(int(v, 16) for v in re.findall(r'0x([0-9a-f]{2})', body))
        assert blob.startswith(b'DXBC')
        assert name + ' SHA256: ' + hashlib.sha256(blob).hexdigest() in header
    print('capture RGB shader source/blob digests match')
    sys.exit(0)
if sys.platform != 'win32':
    raise SystemExit('Generate on native Windows with D3DCompiler_47; --check is portable')

compiler = ctypes.WinDLL('d3dcompiler_47.dll', winmode=0x800)
compile_shader = compiler.D3DCompile
compile_shader.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_char_p,
                          ctypes.c_void_p, ctypes.c_void_p, ctypes.c_char_p,
                          ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint,
                          ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]
compile_shader.restype = ctypes.c_long


def method(blob, index, result):
    table = ctypes.cast(blob, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
    return ctypes.WINFUNCTYPE(result, ctypes.c_void_p)(table[index])


header = ['/* Generated by generate_rgb.py. Source SHA256: ' + digest + ' */',
          '/* Copyright (C) 2026 The RetroArch team. SPDX-License-Identifier: GPL-3.0-or-later */',
          '#ifndef RECORD_CAPTURE_RGB_H', '#define RECORD_CAPTURE_RGB_H']
for name, profile in (('vs', b'vs_5_0'), ('ps', b'ps_5_0')):
    blob, errors = ctypes.c_void_p(), ctypes.c_void_p()
    status = compile_shader(source, len(source), None, None, None,
                            ('capture_' + name).encode(), profile, (1 << 11) | (1 << 15),
                            0, ctypes.byref(blob), ctypes.byref(errors))
    if errors:
        pointer = method(errors, 3, ctypes.c_void_p)(errors)
        message = ctypes.string_at(pointer).decode(errors='replace')
        method(errors, 2, ctypes.c_ulong)(errors)
        if status < 0:
            raise SystemExit(message)
    if status < 0:
        raise SystemExit(f'D3DCompile failed: {status:#x}')
    data = ctypes.string_at(method(blob, 3, ctypes.c_void_p)(blob),
                            method(blob, 4, ctypes.c_size_t)(blob))
    method(blob, 2, ctypes.c_ulong)(blob)
    header += ['/* ' + name + ' SHA256: ' + hashlib.sha256(data).hexdigest() + ' */',
               'static const unsigned char rgc_' + name + '[] = {']
    header += ['   ' + ', '.join(f'0x{v:02x}' for v in data[i:i + 12]) + ','
               for i in range(0, len(data), 12)]
    header += ['};']
header += ['#endif', '']
output.write_bytes('\n'.join(header).encode('utf-8'))
