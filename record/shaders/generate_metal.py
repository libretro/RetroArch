#!/usr/bin/env python3
"""Embed runtime-compiled MSL as bytes without long C89 string literals."""
from pathlib import Path
import hashlib
import sys
root = Path(__file__).resolve().parent
source = (root / 'capture_metal.metal').read_bytes().replace(b'\r\n', b'\n')
data = source + b'\0'
lines = ['/* Generated by generate_metal.py; do not edit. */',
         '/* Source SHA256: ' + hashlib.sha256(source).hexdigest() + ' */',
         '#ifndef RECORD_CAPTURE_METAL_SHADER_H', '#define RECORD_CAPTURE_METAL_SHADER_H',
         'static const unsigned char record_capture_metal_shader[] = {']
lines += ['   ' + ','.join(f'0x{v:02x}' for v in data[i:i+16]) + ','
          for i in range(0, len(data), 16)]
text = '\n'.join(lines + ['};', '#endif', ''])
target = root / 'capture_metal.h'
if sys.argv[1:] == ['--check']:
    assert target.read_text() == text, 'Metal shader embedding differs from source'
    print('Metal capture source/embedding match')
elif sys.argv[1:]:
    raise SystemExit('Usage: generate_metal.py [--check]')
else:
    target.write_text(text)
