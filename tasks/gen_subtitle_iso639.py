#!/usr/bin/env python3
"""Generate container ISO639-2 aliases from a CLDR metadata snapshot.
https://github.com/unicode-org/cldr/blob/7afa5cdb6b7fe7ae65f934c6dbaa374f25b5a616/common/supplemental/supplementalMetadata.xml
"""
import argparse
import hashlib
import re
from pathlib import Path
from xml.etree import ElementTree


def generate(raw):
    aliases = {}
    for row in ElementTree.fromstring(raw).findall('.//languageAlias'):
        source, target = row.get('type'), row.get('replacement')
        if row.get('reason') not in ('overlong', 'bibliographic'):
            continue
        if not re.fullmatch('[a-z]{3}', source) or not re.fullmatch('[a-z]{2}', target):
            continue
        assert source not in aliases
        aliases[source] = target
    assert len(aliases) > 190
    lines = ['/* Generated by gen_subtitle_iso639.py from CLDR supplementalMetadata.xml.',
             ' * Source SHA256: ' + hashlib.sha256(raw).hexdigest(),
             ' * Copyright (c) 2001-2026 Unicode, Inc. See subtitle_iso639.LICENSE. */',
             '', '#ifndef RARCH_SUBTITLE_ISO639_H', '#define RARCH_SUBTITLE_ISO639_H', '',
             'static const char subtitle_iso639_pairs[][5] =', '{']
    lines += ["   {" + ", ".join("'" + c + "'" for c in source + target) + "},"
              for source, target in sorted(aliases.items())]
    lines += ['};', '', '#endif', '']
    return '\n'.join(lines).encode('ascii')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    data = generate(args.source.read_bytes())
    if args.verify:
        assert args.output.read_bytes().replace(b'\r\n', b'\n') == data
    else:
        args.output.write_bytes(data)


if __name__ == '__main__':
    main()
