#!/usr/bin/env python3
"""Double-precision code-value references for the import HDR shaders."""
from pathlib import Path
import math
from functools import lru_cache

def hable(x):
    return (x * (.15*x + .05) + .004)/(x * (.15*x + .5) + .06) - .02/.30

lo, hi = 1., 8.
for _ in range(48):
    gain = (lo + hi)/2
    if hable(gain)/hable(gain*1000/203) < .8: lo = gain
    else: hi = gain
normal = hable(gain*1000/203)

@lru_cache(maxsize=64)
def peak_curve(peak):
    low, high = 1., 8.
    for _ in range(48):
        value = (low + high)/2
        if hable(value)/hable(value*peak/203) < .8: low = value
        else: high = value
    return value, hable(value*peak/203)


def reference(depth, full, transfer, y, u, v, primaries=9, matrix=9, max_cll=0):
    tone_gain, tone_normal = gain, normal
    if transfer == 16 and 400 <= max_cll <= 10000 and max_cll != 1000:
        tone_gain, tone_normal = peak_curve(max_cll)
    scale = 4 if depth else 1
    ym = (1023 if depth else 255) if full else 219*scale
    cm = ym if full else 224*scale
    yy, cb, cr = (y - (0 if full else 16*scale))/ym, (u-128*scale)/cm, (v-128*scale)/cm
    if matrix == 1:
        encoded = [yy+1.5748*cr, yy-.1873242729*cb-.4681242729*cr, yy+1.8556*cb]
    else:
        encoded = [yy+1.4746*cr, yy-.16455313*cb-.57135313*cr, yy+1.8814*cb]
    linear = []
    for x in encoded:
        x = max(0., min(1., x))
        if transfer == 16:
            ep = x**(1/78.84375)
            light = (max(ep-.8359375, 0)/(18.8515625-18.6875*ep))**(1/.1593017578125)*10000/203
        else:
            scene = x*x/3 if x <= .5 else (math.exp((x-.55991073)/.17883277)+.28466892)/12
            light = scene**1.2*1000/203
        linear.append(max(0., min(1., hable(tone_gain*light)/tone_normal)))
    result = []
    gamut = ([(4096,0,0),(0,4096,0),(0,0,4096)] if primaries == 1 else
             [(6801,-2407,-298),(-510,4640,-34),(-75,-412,4583)])
    for row in gamut:
        x = max(0., min(1., sum(a*b for a,b in zip(linear,row))/4096))
        srgb = 12.92*x if x <= .0031308 else 1.055*x**(1/2.4)-.055
        result.append(int(srgb*255+.5))
    return result


def main():
    rows=[]
    for depth in (0,1):
        scale=4 if depth else 1
        for full in (0,1):
            for transfer in (16,18):
                points=[(0 if full else 16*scale,128*scale,128*scale),
                        ((1023 if depth else 255) if full else 235*scale,128*scale,128*scale),
                        (127*scale,128*scale,128*scale),(110*scale,90*scale,170*scale)]
                if depth: points += [(441,361,681)]
                for point in points:
                    rows.append([depth,full,transfer,*point,*reference(depth,full,transfer,*point)])
    out=['/* Generated by hdr_reference.py; RGB bytes for a 1000-nit grade. */',
         'static const unsigned hdr_reference[][9] =', '{']
    out += ['   {' + ', '.join(map(str,row)) + '},' for row in rows]
    out += ['};', '', 'static int hdr_reference_pixel(unsigned depth, unsigned full, unsigned transfer,',
            '      unsigned y, unsigned u, unsigned v, float out[3])', '{', '   unsigned i, j;',
            '   for (i = 0; i < sizeof(hdr_reference) / sizeof(hdr_reference[0]); i++)', '   {',
            '      const unsigned *r = hdr_reference[i];',
            '      if (r[0] == depth && r[1] == full && r[2] == transfer',
            '            && r[3] == y && r[4] == u && r[5] == v)', '      {',
            '         for (j = 0; j < 3; j++)', '            out[j] = (float)r[6 + j] / 255.0f;',
            '         return 1;', '      }', '   }', '   return 0;', '}']
    Path(__file__).with_name('hdr_reference.h').write_text('\n'.join(out)+'\n')


if __name__ == "__main__":
    main()
