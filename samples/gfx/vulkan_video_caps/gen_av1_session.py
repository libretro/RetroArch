#!/usr/bin/env python3
"""Generate sequence-header fixtures for the Vulkan session setup test."""
from pathlib import Path
import subprocess
import tempfile

output = ['/* Generated by gen_av1_session.py using FFmpeg/libaom. */',
          '/* SPDX-License-Identifier: CC0-1.0 */']
names = []
with tempfile.TemporaryDirectory(prefix='av1-session-') as directory:
    for depth in (8, 10):
        for mode, options in (
                ('normal', []), ('still', ['-still-picture', '1']),
                ('grain', ['-aom-params', 'film-grain-test=5'])):
            name = f'av1_sequence_{depth}_{mode}'
            path = Path(directory) / 'sample.obu'
            subprocess.run(['ffmpeg', '-v', 'error', '-f', 'lavfi', '-i',
                'testsrc2=size=256x256:rate=12', '-frames:v', '1', '-an',
                '-c:v', 'libaom-av1', '-cpu-used', '8', '-threads', '2',
                '-pix_fmt', 'yuv420p' if depth == 8 else 'yuv420p10le',
                *options, '-y', str(path)], check=True)
            data, offset, sequence = path.read_bytes(), 0, None
            while offset < len(data):
                header = data[offset]
                offset += 1 + bool(header & 4)
                assert header & 2
                size = 0
                for i in range(8):
                    byte = data[offset]
                    offset += 1
                    size |= (byte & 127) << (7 * i)
                    if not byte & 128:
                        break
                if (header >> 3) & 15 == 1:
                    sequence = data[offset:offset + size]
                    break
                offset += size
            assert sequence
            output += [f'static const uint8_t {name}[] = {{',
                       '   ' + ', '.join(f'0x{b:02x}' for b in sequence), '};']
            names.append((name, depth, mode))
output += ['static const struct av1_sequence_fixture', '{',
           '   const uint8_t *data;', '   size_t size;', '   const char *name;',
           '   unsigned depth, grain;', '} av1_sequence_fixtures[] = {']
output += [f'   {{{name}, sizeof({name}), "{depth}-{mode}", {depth}, {int(mode == "grain")}}},'
           for name, depth, mode in names]
output += ['};', '']
Path(__file__).with_name('av1_session_data.h').write_text('\n'.join(output))
