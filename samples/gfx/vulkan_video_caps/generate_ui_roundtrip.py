#!/usr/bin/env python3
"""Extract production HDR UI math for the offscreen compute oracle."""
from pathlib import Path
import argparse
import re

root = Path(__file__).resolve().parents[3]
folder = root / 'gfx/drivers/vulkan_shaders'
encode = (folder / 'alpha_blend_linear.frag').read_text()
decode = (folder / 'hdr.frag').read_text()
common = (folder / 'hdr_common.glsl').read_text()

def function(text, signature):
    start = text.index(signature)
    pos = text.index('{', start)
    depth = 1
    end = pos + 1
    while depth:
        if text[end] == '{': depth += 1
        if text[end] == '}': depth -= 1
        end += 1
    return text[start:end] + '\n'

pieces = ['#version 450', '// Generated by generate_ui_roundtrip.py.',
    'layout(local_size_x = 1, local_size_y = 1) in;',
    'layout(set = 0, binding = 3, rgba16f) uniform image2D Frame;',
    'layout(push_constant) uniform Params { vec4 args; } params;',
    'struct Composite { uint ExpandGamut; float BrightnessNits; };',
    'Composite global;']
def ui_names(text):
    return re.sub(r'\b(kscRGBWhiteNits|k709to2020|k2020to709|kP3to2020|kExpanded709to2020)\b',
                  r'UI_\1', text)

pieces.append(ui_names(encode[encode.index('const float kscRGBWhiteNits'):encode.index('layout(location')]))
for name in ('kMaxNitsFor2084', 'kscRGBWhiteNits', 'k709to2020', 'k2020to709',
             'kP3to2020', 'kExpanded709to2020'):
    pieces.append(re.search(r'const (?:float|mat3)\s+' + name + r'\s*=[^;]+;', common).group())
for signature in ('vec3 From2020(', 'vec3 HDRUIEncode('):
    pieces.append(ui_names(function(encode, signature)))
for text, signature in [(decode, 'vec3 HDRDecodeGamma('), (decode, 'vec3 To2020('),
                        (decode, 'vec4 To2020('), (common, 'vec3 LinearToST2084('),
                        (common, 'vec3 ST2084ToLinear('), (common, 'vec3 HDR10ToscRGB('),
                        (decode, 'vec3 HDR10(')]:
    pieces.append(function(text, signature))
pieces.append("""
void main()
{
   ivec2 p = ivec2(gl_GlobalInvocationID.xy);
   if (any(greaterThanEqual(p, imageSize(Frame)))) return;
   global.ExpandGamut = uint(params.args.y);
   global.BrightnessNits = params.args.x;
   vec4 source = imageLoad(Frame, p);
   vec3 encoded = HDRUIEncode(source.rgb, params.args.x, params.args.y);
   encoded.xy = unpackHalf2x16(packHalf2x16(encoded.xy));
   encoded.z = unpackHalf2x16(packHalf2x16(encoded.zz)).x;
   vec3 value = To2020(vec4(HDRDecodeGamma(encoded), source.a)).rgb;
   if (params.args.z < 1.5)
      value = HDR10ToscRGB(HDR10(value));
   else
      value = (value * k2020to709) * (global.BrightnessNits / 80.0);
   imageStore(Frame, p, vec4(value, source.a));
}
""")
result = '\n'.join(line.rstrip() for line in '\n'.join(pieces).splitlines()) + '\n'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
target = Path(__file__).with_name('ui_roundtrip.comp')
if args.check:
    if target.read_text() != result:
        raise SystemExit('Regenerate ui_roundtrip.comp and its SPIR-V')
else:
    target.write_text(result)
