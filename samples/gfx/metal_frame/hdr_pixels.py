#!/usr/bin/env python3
"""Independent double-precision PQ/HLG to scRGB vectors for GPU acceptance."""
import argparse
import math
from pathlib import Path


def code(fmt, x, y, plane, channel):
    scale, maximum = (4, 1023) if fmt >= 2 else (1, 255)
    black, white = (0, maximum) if fmt & 1 else (16 * scale, 235 * scale)
    center = 128 * scale
    low, high = (0, maximum) if fmt & 1 else (16 * scale, 240 * scale)
    ys = [black, black + 1, black + 4 * scale, black + 18 * scale,
          (black + white) // 2, white - 1, white,
          min(white + 1, maximum), maximum, 0]
    cb = [center, center - 40 * scale, center + 40 * scale, low, high]
    cr = [center, center + 24 * scale, center - 48 * scale, high, low]
    return ys[(x + y * 3) % 10] if not plane else (
        cr[(x * 2 + y * 3) % 5] if channel else cb[(x + y) % 5])


def display(rgb, hlg):
    if hlg:
        scene = [v * v / 3 if v <= 0.5 else
                 (math.exp((v - 0.55991073) / 0.17883277) + 0.28466892) / 12
                 for v in rgb]
        luminance = sum(v * k for v, k in zip(scene, (0.2627, 0.6780, 0.0593)))
        linear = [v * 12.5 * luminance ** 0.2 for v in scene]
    else:
        m1, m2 = 2610 / 16384, 2523 / 32
        c1, c2, c3 = 3424 / 4096, 2413 / 128, 2392 / 128
        linear = [125 * (max(v ** (1 / m2) - c1, 0) /
                         (c2 - c3 * v ** (1 / m2))) ** (1 / m1) for v in rgb]
    matrix = ((1.660491, -0.587641, -0.072850),
              (-0.124550, 1.132900, -0.008349),
              (-0.018151, -0.100579, 1.118730))
    return [sum(v * k for v, k in zip(linear, row)) for row in matrix] + [1.0]


def generate():
    assert max(abs(v - 125) for v in display([1, 1, 1], False)[:3]) < 0.001
    assert max(abs(v - 12.5) for v in display([1, 1, 1], True)[:3]) < 0.001
    assert display([0, 0, 0], False) == [0, 0, 0, 1]
    assert display([0, 0, 0], True) == [0, 0, 0, 1]
    rows = []
    kr, kb = 0.2627, 0.0593
    kg = 1 - kr - kb
    for position in range(3):
        for fmt in range(4):
            for hlg in range(2):
                row = []
                scale, maximum = (4, 1023) if fmt >= 2 else (1, 255)
                full = fmt & 1
                for y in range(5):
                    for x in range(7):
                        luma = (code(fmt, x + 2, y + 2, 0, 0) -
                                (0 if full else 16 * scale)) / (maximum if full else 219 * scale)
                        if position:
                            at_x = (x + 2) / 2
                            at_y = (y + 2) / 2 - (0.25 if position == 1 else 0)
                            left, top = math.floor(at_x), math.floor(at_y)
                            def sample(channel):
                                total = 0.0
                                for dy in range(2):
                                    for dx in range(2):
                                        weight = ((at_x - left) if dx else (1 - at_x + left))
                                        weight *= ((at_y - top) if dy else (1 - at_y + top))
                                        total += weight * code(fmt, min(4, max(0, left + dx)),
                                                               min(3, max(0, top + dy)), 1, channel)
                                return total
                            u, v = sample(0), sample(1)
                        else:
                            u = code(fmt, (x + 2) // 2, (y + 2) // 2, 1, 0)
                            v = code(fmt, (x + 2) // 2, (y + 2) // 2, 1, 1)
                        cb = (u - 128 * scale) / (maximum if full else 224 * scale)
                        cr = (v - 128 * scale) / (maximum if full else 224 * scale)
                        rgb = (luma + 2 * (1 - kr) * cr,
                               luma - 2 * kb * (1 - kb) / kg * cb - 2 * kr * (1 - kr) / kg * cr,
                               luma + 2 * (1 - kb) * cb)
                        row += display([min(1, max(0, v)) for v in rgb], hlg)
                assert min(row) < 0 and max(row) > 1
                rows.append(row)
    text = '/* Generated by hdr_pixels.py; PQ/HLG linear scRGB, no tone map. */\n'
    text += 'static const float hdr_expected[24][140] = {\n'
    for row in rows:
        text += '   {\n'
        for start in range(0, len(row), 8):
            values = []
            for value in row[start:start + 8]:
                word = format(value, '.9g')
                if '.' not in word and 'e' not in word:
                    word += '.0'
                values.append(word + 'f')
            text += '      ' + ', '.join(values) + ',\n'
        text += '   },\n'
    return text + '};\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).with_suffix('.h')
    expected = generate()
    if args.verify:
        assert target.read_text() == expected, 'HDR vectors differ; regenerate explicitly'
    else:
        target.write_text(expected)
    print('Metal HDR reference: 24 cropped PQ/HLG/chroma vectors and absolute white checks passed')
