#!/bin/sh
# Regenerates d3d11_video_decode_test_data.h: short x264 streams, in
# MP4, covering what a DXVA decoder is told - CAVLC and CABAC,
# B-pyramids, several references, weighted prediction, slices, 8x8
# transforms, scaling matrices (the JVT ones and lists of our own) and
# a cropped picture. Needs ffmpeg with libx264.
set -eu

dir=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
out="$dir/d3d11_video_decode_test_data.h"

enc()
{
   name=$1 src=$2 frames=$3
   shift 3
   ffmpeg -v error -y -f lavfi -i "$src" -frames:v "$frames" \
      -c:v libx264 -pix_fmt yuv420p "$@" "$tmp/$name.mp4"
}

enc baseline "testsrc2=s=176x144:r=25" 16 \
   -profile:v baseline -preset medium -g 8
enc main_bpyr "testsrc2=s=176x144:r=25" 20 \
   -profile:v main -preset slow \
   -x264-params bframes=3:b-pyramid=normal:ref=4:keyint=12
enc high_slices "mandelbrot=s=176x144:r=25" 16 \
   -profile:v high -preset medium \
   -x264-params slices=4:weightp=2:bframes=2:8x8dct=1
enc high_jvt "testsrc2=s=176x144:r=25" 12 \
   -profile:v high -preset medium -x264-params cqm=jvt:bframes=2
enc high_cqm "testsrc2=s=176x144:r=25" 12 \
   -profile:v high -preset medium -x264-params \
"bframes=2:cqm4i=6,12,12,18,18,18,24,24,24,24,30,30,30,36,36,40:\
cqm4p=12,14,14,18,18,18,22,22,22,22,26,26,26,30,30,32:\
cqm8i=8,10,10,12,12,12,14,14,14,14,16,16,16,16,16,18,18,18,18,18,18,20,20,20,20,20,20,20,22,22,22,22,22,22,22,22,24,24,24,24,24,24,24,26,26,26,26,26,26,28,28,28,28,28,30,30,30,30,32,32,32,34,34,36:\
cqm8p=10,12,12,14,14,14,16,16,16,16,18,18,18,18,18,20,20,20,20,20,20,22,22,22,22,22,22,22,24,24,24,24,24,24,24,24,26,26,26,26,26,26,26,28,28,28,28,28,28,30,30,30,30,30,32,32,32,32,34,34,34,36,36,38"
enc cropped "testsrc2=s=170x122:r=25" 12 \
   -profile:v high -preset medium -x264-params bframes=2

{
   echo "/* Generated by gen_data.sh; do not edit. */"
   echo "#ifndef D3D11_VIDEO_DECODE_TEST_DATA_H"
   echo "#define D3D11_VIDEO_DECODE_TEST_DATA_H"
   echo
   for n in baseline main_bpyr high_slices high_jvt high_cqm cropped; do
      echo "static const unsigned char stream_$n[] = {"
      od -An -v -tu1 "$tmp/$n.mp4" | awk '{ s = "  "; for (i = 1; i <= NF; i++) s = s $i ","; print s }'
      echo "};"
      echo
   done
   echo "#endif"
} > "$out"
echo "wrote $out"
