#!/usr/bin/env python3
"""Regenerate HEVC device fixtures with FFmpeg/libx265 (test tools only)."""
from pathlib import Path
import struct
import subprocess
import tempfile


def array(lines, name, data):
    lines.append('static const uint8_t %s[] = {' % name)
    lines.extend('   ' + ','.join(str(v) for v in data[i:i + 16]) + ','
                 for i in range(0, len(data), 16))
    lines.append('};')


out = Path(__file__).with_name('hevc_device_data.h')
lines = ['/* Generated by gen_hevc_data.py; FFmpeg/libx265. */',
         '#ifndef HEVC_DEVICE_DATA_H', '#define HEVC_DEVICE_DATA_H']
with tempfile.TemporaryDirectory() as tmp:
    for depth in (8, 10):
        for kind in ('intra', 'ip', 'bpyr', 'wpp', 'crop', 'repeat'):
            name = 'hevc_%s%d' % (kind, depth)
            path = Path(tmp) / (name + '.mp4')
            size = '250x242' if kind == 'crop' else '256x256'
            source = 'color=blue' if kind == 'intra' else 'testsrc2'
            params = ('pools=1' if kind == 'wpp' else 'pools=none')
            params += ':frame-threads=1:ctu=64:log-level=error:keyint=8'
            params += ':wpp=1' if kind == 'wpp' else ':wpp=0'
            params += ':bframes=3:b-adapt=0:b-pyramid=1:ref=4' if kind == 'bpyr' else ':bframes=0'
            params += ':lossless=1' if kind == 'intra' else ':qp=24'
            if kind == 'repeat':
                params += ':repeat-headers=1'
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi',
                            '-i', source + (':s=' if kind == 'intra' else '=s=') + size + ':r=25',
                            '-frames:v', '1' if kind == 'intra' else '12',
                            '-c:v', 'libx265', '-pix_fmt',
                            'yuv420p10le' if depth == 10 else 'yuv420p',
                            '-x265-params', params, '-tag:v', 'hvc1', str(path)], check=True)
            data = path.read_bytes()
            if kind == 'intra':
                for box, label in ((b'hvcC', 'config'), (b'mdat', 'sample')):
                    at = data.index(box)
                    length = struct.unpack('>I', data[at - 4:at])[0]
                    array(lines, 'hevc_device_%s%d' % (label, depth), data[at + 4:at - 4 + length])
            else:
                array(lines, name, data)
                raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(path),
                                               '-f', 'rawvideo', '-pix_fmt',
                                               'yuv420p10le' if depth == 10 else 'yuv420p', '-'])
                width, height = map(int, size.split('x'))
                frame_size = width * height * 3 // 2 * (2 if depth == 10 else 1)
                assert len(raw) == frame_size * 12
                hashes = []
                for start in range(0, len(raw), frame_size):
                    value = 2166136261
                    for byte in raw[start:start + frame_size]:
                        value = ((value ^ byte) * 16777619) & 0xffffffff
                    hashes.append(value)
                lines.append('static const uint32_t %s_hash[] = {' % name)
                lines.append('   ' + ','.join('UINT32_C(0x%08x)' % value for value in hashes))
                lines.append('};')
lines.append('#endif')
out.write_text('\n'.join(lines) + '\n')
