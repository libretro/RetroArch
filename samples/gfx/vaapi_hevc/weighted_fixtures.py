#!/usr/bin/env python3
"""Generate multi-row WPP weighted-B HEVC fixtures with FFmpeg pixel CRCs."""
import hashlib
import argparse
import json
from pathlib import Path
import subprocess
import re
import sys
import tempfile
import zlib

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'videotoolbox_hevc'))
import codec_fixtures as base
from sequence_fixtures import unpack

WIDTH, HEIGHT, COUNT = 176, 144, 8

def generate(trace_dir=None):
    text = '/* Generated by weighted_fixtures.py; 176x144 WPP weighted-B streams. */\n'
    cases = []
    with tempfile.TemporaryDirectory(prefix='va-hevc-weighted-') as directory:
        tmp = Path(directory)
        for depth, full in [(8, False), (10, False), (8, True), (10, True)]:
            name = 'weighted_main%d_%s' % (depth, 'full' if full else 'limited')
            movie = tmp / (name + '.mp4')
            pixfmt = 'yuv420p' if depth == 8 else 'yuv420p10le'
            params = ('pools=1:frame-threads=1:log-level=error:wpp=1:ctu=64:'
                      'bframes=2:b-adapt=0:b-pyramid=0:weightp=1:weightb=1:'
                      'scenecut=0:keyint=64:min-keyint=64:ref=2:'
                      'colorprim=bt709:transfer=bt709:colormatrix=bt709:range='
                      + ('full' if full else 'limited'))
            base.run([base.FFMPEG, '-v', 'error', '-f', 'lavfi', '-i',
                      'testsrc2=s=176x144:r=10', '-vf', 'fade=t=in:st=0:d=0.7',
                      '-frames:v', str(COUNT), '-pix_fmt', pixfmt,
                      '-color_range', 'pc' if full else 'tv', '-c:v', 'libx265',
                      '-profile:v', 'main' if depth == 8 else 'main10',
                      '-crf', '24', '-x265-params', params, '-tag:v', 'hvc1', '-y', str(movie)])
            probe = json.loads(base.run(['ffprobe', '-v', 'error', '-select_streams', 'v:0',
                      '-show_streams', '-show_packets', '-show_entries',
                      'stream=extradata:packet=data,pts,dts', '-show_data', '-of', 'json', str(movie)]))
            hvcc = unpack(probe['streams'][0]['extradata'])
            packets = []
            for entry in probe['packets']:
                vcl = [unit for unit in base.sample_nals(unpack(entry['data']))
                       if ((unit[0] >> 1) & 63) <= 31]
                assert len(vcl) == 1
                packets.append(b''.join(len(unit).to_bytes(4, 'big') + unit for unit in vcl))
            assert len(packets) == COUNT
            pts = [int(entry['pts']) for entry in probe['packets']]
            assert len(set(pts)) == COUNT
            order = [sorted(pts).index(value) for value in pts]
            assert order != list(range(COUNT))
            stream = b''.join(b'\0\0\0\1' + unit for unit in
                      list(base.parameter_nals(hvcc)) + [n for packet in packets for n in base.sample_nals(packet)])
            elementary = tmp / 'oracle.hevc'
            elementary.write_bytes(stream)
            sample_range = 'full' if full else 'limited'
            raw = base.run([base.FFMPEG, '-v', 'error', '-threads', '1', '-filter_threads', '1', '-i', str(elementary),
                            '-frames:v', str(COUNT), '-vf', 'scale=in_range=%s:out_range=%s' % (sample_range, sample_range),
                            '-color_range', 'pc' if full else 'tv', '-f', 'rawvideo', '-pix_fmt', pixfmt, '-'])
            sizes = [WIDTH * HEIGHT * (2 if depth == 10 else 1)]
            sizes += [sizes[0] // 4] * 2
            assert len(raw) == COUNT * sum(sizes)
            checksums, offset = [], 0
            frames = json.loads(base.run(['ffprobe', '-v', 'error', '-show_frames',
                '-show_entries', 'frame=pict_type', '-of', 'json', str(elementary)]))['frames']
            types = [f['pict_type'] for f in frames]
            assert types == ['I', 'B', 'B', 'P', 'B', 'B', 'P', 'P'], types
            for _ in range(COUNT):
                crc = []
                for size in sizes:
                    crc.append(zlib.crc32(raw[offset:offset + size]))
                    offset += size
                checksums.append(crc)
            text += base.array(name + '_hvcc', hvcc)
            for i, packet in enumerate(packets):
                text += base.array(name + '_' + str(i), packet)
            # trace_headers independently verifies the encoded syntax, not just encoder flags.
            trace = subprocess.run([base.FFMPEG, '-v', 'info', '-i', str(elementary),
                     '-c:v', 'copy', '-bsf:v', 'trace_headers', '-f', 'null', '-'],
                     capture_output=True, check=True).stderr.decode()
            trace = re.sub(r'(?<=@ )0x[0-9a-fA-F]+', '0xADDR', trace)
            assert 'num_entry_point_offsets' in trace and 'luma_weight_l1_flag' in trace
            if trace_dir:
                trace_dir.mkdir(parents=True, exist_ok=True)
                (trace_dir / (name + '.trace.txt')).write_text(trace, encoding='utf-8', newline='\n')
            text += 'static const sequence_packet_t %s_packets[] = {\n' % name
            for i, display in enumerate(order):
                n = name + '_' + str(i)
                text += '   {%d, %s, sizeof(%s), {%s}, %d, %d},\n' % (
                    int(probe['packets'][i]['dts']), n, n,
                    ', '.join('0x%08xu' % value for value in checksums[display]),
                    display, {'I': 2, 'P': 1, 'B': 0}[types[display]])
            text += '};\n'
            cases.append(dict(name=name, depth=depth, full=int(full), order=order, types=types,
                              crc=checksums, hvcc_sha256=hashlib.sha256(hvcc).hexdigest(),
                              packet_sha256=[hashlib.sha256(p).hexdigest() for p in packets],
                              trace_sha256=hashlib.sha256(trace.encode()).hexdigest()))
    text += 'static const sequence_case_t weighted_cases[] = {\n'
    for case in cases:
        n = case['name']
        text += ('   {{"%s", %s_hvcc, sizeof(%s_hvcc), %s_0, sizeof(%s_0), %d, %d, {%s}}, %s_packets, 1},\n'
                 % (n, n, n, n, n, case['depth'], case['full'],
                    ', '.join('0x%08xu' % v for v in case['crc'][0]), n))
    text += '};\n'
    (HERE / 'weighted_data.h').write_text(text, encoding='utf-8', newline='\n')
    (HERE / 'weighted_fixtures.json').write_text(json.dumps(dict(width=WIDTH, height=HEIGHT,
        count=COUNT, cases=cases, header_sha256=hashlib.sha256(text.encode()).hexdigest(),
        ffmpeg=base.run([base.FFMPEG, '-version']).decode().splitlines()[0]), indent=2) + '\n', encoding='utf-8', newline='\n')
    print('Generated four WPP weighted-B streams and independent FFmpeg CRCs')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--trace-dir', type=Path)
    generate(parser.parse_args().trace_dir)
