#!/usr/bin/env python3
"""Generate or verify eight-picture Main/Main10 I/P sequences."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import zlib

import codec_fixtures as base

HERE = Path(__file__).resolve().parent
COUNT = 8
PROBE = os.environ.get('FFPROBE', 'ffprobe')


def unpack(dump):
    return bytes.fromhex(''.join(line.split(':', 1)[1].split('  ', 1)[0].strip()
                                for line in dump.splitlines() if ':' in line))


def moving_pixels(depth, full, frame):
    raw = base.pixels(depth, full)
    result = bytearray()
    offset = 0
    pel = 2 if depth == 10 else 1
    for width in [64, 32, 32]:
        stride = width * pel
        plane = raw[offset:offset + width * stride]
        offset += len(plane)
        shift = (frame * 3 % width) * pel
        for y in range(width):
            row = (y + frame * 2) % width
            line = plane[row * stride:(row + 1) * stride]
            result += line[shift:] + line[:shift]
    return result


def oracle(hvcc, packets, depth, full, tmp):
    units = list(base.parameter_nals(hvcc))
    for packet in packets:
        units.extend(base.sample_nals(packet))
    source = tmp / 'sequence.hevc'
    source.write_bytes(b''.join(b'\0\0\0\1' + unit for unit in units))
    sample_range = 'full' if full else 'limited'
    decoded = subprocess.run([base.FFMPEG, '-v', 'info', '-threads', '1', '-filter_threads', '1',
        '-i', str(source), '-frames:v', str(COUNT), '-vf',
        'showinfo,scale=in_range=%s:out_range=%s' % (sample_range, sample_range),
        '-color_range', 'pc' if full else 'tv', '-f', 'rawvideo', '-pix_fmt',
        'yuv420p' if depth == 8 else 'yuv420p10le', '-'],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
    types = re.findall(rb'\[Parsed_showinfo_[^\]]+\].*? type:([IPB])\b', decoded.stderr)
    assert types == [b'I'] + [b'P'] * (COUNT - 1), types
    raw = decoded.stdout
    sizes = [4096, 1024, 1024]
    if depth == 10:
        sizes = [size * 2 for size in sizes]
    assert len(raw) == COUNT * sum(sizes)
    checksums = []
    offset = 0
    for _ in packets:
        crc = []
        for size in sizes:
            crc.append(zlib.crc32(raw[offset:offset + size]))
            offset += size
        checksums.append(crc)
    assert len({tuple(crc) for crc in checksums}) == COUNT
    return checksums


def generate():
    text = '/* Generated by sequence_fixtures.py; 64x64 BT.709 I/P sequences. */\n'
    cases = []
    with tempfile.TemporaryDirectory(prefix='vt-hevc-sequence-') as directory:
        tmp = Path(directory)
        for depth, full in [(8, False), (10, False), (8, True), (10, True)]:
            name = 'main%d_%s' % (depth, 'full' if full else 'limited')
            source, encoded = tmp / 'input.yuv', tmp / 'sequence.mp4'
            source.write_bytes(b''.join(moving_pixels(depth, full, frame) for frame in range(COUNT)))
            params = ('pools=1:frame-threads=1:log-level=error:bframes=0:scenecut=0:'
                      'keyint=30:min-keyint=30:ref=1:wpp=0:ctu=32:min-cu-size=8:'
                      'colorprim=bt709:transfer=bt709:colormatrix=bt709:range='
                      + ('full' if full else 'limited'))
            base.run([base.FFMPEG, '-v', 'error', '-f', 'rawvideo', '-pixel_format',
                'yuv420p' if depth == 8 else 'yuv420p10le', '-video_size', '64x64',
                '-framerate', '30000/1001', '-color_range', 'pc' if full else 'tv',
                '-i', str(source), '-frames:v', str(COUNT), '-c:v', 'libx265',
                '-profile:v', 'main' if depth == 8 else 'main10', '-crf', '18',
                '-x265-params', params, '-tag:v', 'hvc1', '-y', str(encoded)])
            probe = json.loads(base.run([PROBE, '-v', 'error', '-select_streams', 'v:0',
                '-show_streams', '-show_packets', '-show_entries', 'stream=extradata:packet=data',
                '-show_data', '-of', 'json', str(encoded)]))
            hvcc = unpack(probe['streams'][0]['extradata'])
            assert hvcc[1] & 31 == (1 if depth == 8 else 2)
            packets = []
            for entry in probe['packets']:
                vcl = [unit for unit in base.sample_nals(unpack(entry['data']))
                       if ((unit[0] >> 1) & 63) <= 31]
                assert len(vcl) == 1
                packets.append(b''.join(len(unit).to_bytes(4, 'big') + unit for unit in vcl))
            assert len(packets) == COUNT
            crc = oracle(hvcc, packets, depth, full, tmp)
            text += base.array('sequence_' + name + '_hvcc', hvcc)
            for index, packet in enumerate(packets):
                text += base.array('sequence_%s_%d' % (name, index), packet)
            text += 'static const sequence_packet_t sequence_%s_packets[] = {\n' % name
            for index, checksums in enumerate(crc):
                n = 'sequence_%s_%d' % (name, index)
                text += '   {%s, sizeof(%s), {%s}},\n' % (
                    n, n, ', '.join('0x%08xu' % value for value in checksums))
            text += '};\n'
            cases.append(dict(name=name, depth=depth, full=int(full), crc=crc,
                types=['I'] + ['P'] * (COUNT - 1), hvcc_sha256=hashlib.sha256(hvcc).hexdigest(),
                packet_sha256=[hashlib.sha256(packet).hexdigest() for packet in packets]))
    text += 'static const sequence_case_t sequence_cases[] = {\n'
    for case in cases:
        n = case['name']
        text += ('   {{"sequence_%s", sequence_%s_hvcc, sizeof(sequence_%s_hvcc), '
                 'sequence_%s_0, sizeof(sequence_%s_0), %d, %d, {%s}}, sequence_%s_packets},\n') % (
                 n, n, n, n, n, case['depth'], case['full'],
                 ', '.join('0x%08xu' % value for value in case['crc'][0]), n)
    text += '};\n'
    (HERE / 'sequence_data.h').write_text(text, encoding='utf8', newline='\n')
    manifest = dict(width=64, height=64, count=COUNT, cases=cases,
        header_sha256=hashlib.sha256(text.encode()).hexdigest(),
        ffmpeg_version=base.run([base.FFMPEG, '-version']).decode().splitlines()[0])
    (HERE / 'sequence_fixtures.json').write_text(json.dumps(manifest, indent=2) + '\n',
        encoding='utf8', newline='\n')


def verify():
    header = (HERE / 'sequence_data.h').read_bytes().replace(b'\r\n', b'\n')
    manifest = json.loads((HERE / 'sequence_fixtures.json').read_text())
    assert manifest['count'] == COUNT and manifest['width'] == manifest['height'] == 64
    assert hashlib.sha256(header).hexdigest() == manifest['header_sha256']
    arrays = {name: bytes(int(value, 16) for value in re.findall(r'0x([0-9a-f]{2})', body))
              for name, body in re.findall(r'static const uint8_t (\w+)\[\] = \{(.*?)\};', header.decode(), re.S)}
    with tempfile.TemporaryDirectory(prefix='vt-hevc-sequence-oracle-') as directory:
        for case in manifest['cases']:
            hvcc = arrays['sequence_' + case['name'] + '_hvcc']
            packets = [arrays['sequence_%s_%d' % (case['name'], index)] for index in range(COUNT)]
            assert hvcc[1] & 31 == (1 if case['depth'] == 8 else 2)
            assert hashlib.sha256(hvcc).hexdigest() == case['hvcc_sha256']
            assert [hashlib.sha256(packet).hexdigest() for packet in packets] == case['packet_sha256']
            assert case['types'] == ['I'] + ['P'] * (COUNT - 1)
            assert oracle(hvcc, packets, case['depth'], case['full'], Path(directory)) == case['crc'], case['name']
    print('VideoToolbox sequence corpus: four eight-picture I/P streams match the FFmpeg oracle')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--generate', action='store_true')
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    if args.generate:
        generate()
    if args.verify:
        verify()
    if not args.generate and not args.verify:
        parser.error('choose --generate or --verify')
