#!/usr/bin/env python3
"""Generate or independently verify the embedded Main/Main10 codec fixtures."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import struct
import subprocess
import tempfile
import zlib

HERE = Path(__file__).resolve().parent
WIDTH = HEIGHT = 64
FFMPEG = os.environ.get('FFMPEG', 'ffmpeg')


def run(args):
    return subprocess.check_output(args, stderr=subprocess.PIPE)


def nals(data):
    return [unit.rstrip(b'\0') for unit in re.split(b'\x00\x00(?:\x00)?\x01', data) if unit]


def parameter_nals(hvcc):
    assert len(hvcc) >= 23 and hvcc[0] == 1 and hvcc[21] & 3 == 3
    pos = 23
    for _ in range(hvcc[22]):
        count = int.from_bytes(hvcc[pos+1:pos+3], 'big')
        pos += 3
        for _ in range(count):
            size = int.from_bytes(hvcc[pos:pos+2], 'big')
            pos += 2
            assert size >= 3 and pos + size <= len(hvcc)
            yield hvcc[pos:pos+size]
            pos += size
    assert pos == len(hvcc)


def sample_nals(sample):
    pos = 0
    while pos < len(sample):
        size = int.from_bytes(sample[pos:pos+4], 'big')
        pos += 4
        assert size >= 3 and pos + size <= len(sample)
        yield sample[pos:pos+size]
        pos += size
    assert pos == len(sample)


def oracle(hvcc, sample, depth, full, tmp):
    stream = b''.join(b'\0\0\0\1' + unit for unit in list(parameter_nals(hvcc)) + list(sample_nals(sample)))
    source = tmp/'oracle.hevc'
    source.write_bytes(stream)
    color_range = 'full' if full else 'limited'
    raw = run([FFMPEG, '-v', 'error', '-threads', '1', '-filter_threads', '1', '-i', str(source),
               '-frames:v', '1', '-vf', 'scale=in_range=%s:out_range=%s' % (color_range,color_range),
               '-color_range', 'pc' if full else 'tv', '-f', 'rawvideo', '-pix_fmt',
               'yuv420p' if depth == 8 else 'yuv420p10le', '-'])
    sizes = [WIDTH * HEIGHT, WIDTH * HEIGHT // 4, WIDTH * HEIGHT // 4]
    if depth == 10:
        sizes = [size * 2 for size in sizes]
    assert len(raw) == sum(sizes)
    offset = 0
    checksums = []
    for size in sizes:
        checksums.append(zlib.crc32(raw[offset:offset+size]))
        offset += size
    return checksums


def pixels(depth, full):
    result = bytearray()
    for plane in range(3):
        width, height = (WIDTH, HEIGHT) if plane == 0 else (WIDTH//2, HEIGHT//2)
        low = 0 if full else (16 if depth == 8 else 64)
        span = (1 << depth) if full else ((220 if plane == 0 else 225) << (depth - 8))
        for y in range(height):
            for x in range(width):
                value = low + (x * (5 + plane * 7) + y * (3 + plane * 5) + plane * 39) % span
                result += bytes([value]) if depth == 8 else struct.pack('<H', value)
    return result


def array(name, data):
    rows = [', '.join('0x%02x' % value for value in data[i:i+12]) for i in range(0,len(data),12)]
    return 'static const uint8_t %s[] = {\n   %s\n};\n' % (name, ',\n   '.join(rows))


def generate():
    text = '/* Generated by codec_fixtures.py; 64x64 BT.709 spatial I pictures. */\n'
    cases = []
    with tempfile.TemporaryDirectory(prefix='vt-hevc-fixtures-') as directory:
        tmp = Path(directory)
        for depth, full in [(8,False),(10,False),(8,True),(10,True)]:
            name = 'main%d_%s' % (depth, 'full' if full else 'limited')
            source, encoded, mp4 = tmp/'input.yuv', tmp/'frame.hevc', tmp/'frame.mp4'
            source.write_bytes(pixels(depth, full))
            fmt = 'yuv420p' if depth == 8 else 'yuv420p10le'
            params = ('pools=1:frame-threads=1:log-level=error:repeat-headers=1:'
                      'bframes=0:keyint=30:min-keyint=30:ref=1:wpp=0:ctu=32:min-cu-size=8:'
                      'colorprim=bt709:transfer=bt709:colormatrix=bt709:range=' + ('full' if full else 'limited'))
            run([FFMPEG,'-v','error','-f','rawvideo','-pixel_format',fmt,'-video_size','64x64',
                 '-framerate','1','-color_range','pc' if full else 'tv','-i',str(source),
                 '-frames:v','1','-c:v','libx265','-profile:v','main' if depth==8 else 'main10',
                 '-crf','18','-x265-params',params,'-f','hevc','-y',str(encoded)])
            run([FFMPEG,'-v','error','-i',str(encoded),'-c:v','copy','-tag:v','hvc1','-y',str(mp4)])
            probe = json.loads(run([os.environ.get('FFPROBE','ffprobe'),'-v','error','-select_streams','v:0',
                '-show_entries','stream=extradata','-show_data','-of','json',str(mp4)]))
            dump = probe['streams'][0]['extradata']
            hvcc = bytes.fromhex(''.join(line.split(':',1)[1].split('  ',1)[0].strip()
                                        for line in dump.splitlines() if ':' in line))
            assert hvcc[1] & 31 == (1 if depth == 8 else 2)
            vcl = [unit for unit in nals(encoded.read_bytes()) if ((unit[0] >> 1) & 63) <= 31]
            assert len(vcl) == 1
            sample = b''.join(len(unit).to_bytes(4,'big') + unit for unit in vcl)
            checksums = oracle(hvcc, sample, depth, full, tmp)
            text += array('codec_'+name+'_hvcc',hvcc) + array('codec_'+name+'_sample',sample)
            cases.append(dict(name=name,depth=depth,full=int(full),crc=checksums,
                hvcc_sha256=hashlib.sha256(hvcc).hexdigest(),sample_sha256=hashlib.sha256(sample).hexdigest()))
    text += 'static const codec_case_t codec_cases[] = {\n'
    for case in cases:
        n=case['name']
        text += ('   {"%s", codec_%s_hvcc, sizeof(codec_%s_hvcc), '
                 'codec_%s_sample, sizeof(codec_%s_sample), %d, %d, {%s}},\n') % (
                     n,n,n,n,n,case['depth'],case['full'],', '.join('0x%08xu' % crc for crc in case['crc']))
    text += '};\n'
    (HERE/'codec_data.h').write_text(text,encoding='utf8',newline='\n')
    manifest=dict(width=WIDTH,height=HEIGHT,cases=cases,
                  header_sha256=hashlib.sha256(text.encode()).hexdigest(),
                  ffmpeg_version=run([FFMPEG,'-version']).decode().splitlines()[0])
    (HERE/'codec_fixtures.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf8',newline='\n')


def verify():
    # Git may check C headers out with CRLF on Windows.
    header=(HERE/'codec_data.h').read_bytes().replace(b'\r\n',b'\n')
    manifest=json.loads((HERE/'codec_fixtures.json').read_text())
    assert hashlib.sha256(header).hexdigest()==manifest['header_sha256']
    arrays={name:bytes(int(value,16) for value in re.findall(r'0x([0-9a-f]{2})',body))
            for name,body in re.findall(r'static const uint8_t (\w+)\[\] = \{(.*?)\};',header.decode(),re.S)}
    with tempfile.TemporaryDirectory(prefix='vt-hevc-oracle-') as directory:
        for case in manifest['cases']:
            hvcc=arrays['codec_'+case['name']+'_hvcc']; sample=arrays['codec_'+case['name']+'_sample']
            assert hvcc[1] & 31 == (1 if case['depth'] == 8 else 2)
            assert hashlib.sha256(hvcc).hexdigest()==case['hvcc_sha256']
            assert hashlib.sha256(sample).hexdigest()==case['sample_sha256']
            assert oracle(hvcc,sample,case['depth'],case['full'],Path(directory))==case['crc'],case['name']
    print('VideoToolbox codec corpus: four embedded fixtures match the FFmpeg oracle')


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--generate',action='store_true')
    parser.add_argument('--verify',action='store_true')
    args=parser.parse_args()
    if args.generate: generate()
    if args.verify: verify()
    if not args.generate and not args.verify: parser.error('choose --generate or --verify')
