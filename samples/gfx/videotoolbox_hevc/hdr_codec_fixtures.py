#!/usr/bin/env python3
"""Generate/verify coded BT.2020 PQ/HLG HEVC without altering the SDR corpus."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile
import codec_fixtures as codec

HERE = Path(__file__).resolve().parent


def generate():
    text = '/* Generated by hdr_codec_fixtures.py; coded 64x64 BT.2020 PQ/HLG. */\n'
    cases = []
    with tempfile.TemporaryDirectory(prefix='vt-hevc-hdr-') as directory:
        tmp = Path(directory)
        for depth in (8, 10):
            for full in (0, 1):
                for transfer, name_trc in ((16, 'smpte2084'), (18, 'arib-std-b67')):
                    name = 'main%d_%s_%s' % (depth, 'full' if full else 'limited', 'pq' if transfer == 16 else 'hlg')
                    source, stream, container = tmp/'input.yuv', tmp/'frame.hevc', tmp/'frame.mp4'
                    source.write_bytes(codec.pixels(depth, full))
                    params = ('pools=1:frame-threads=1:log-level=error:repeat-headers=1:'
                              'bframes=0:keyint=30:min-keyint=30:ref=1:wpp=0:ctu=32:min-cu-size=8:'
                              'colorprim=9:transfer=%d:colormatrix=9:range=%s' %
                              (transfer, 'full' if full else 'limited'))
                    codec.run([codec.FFMPEG, '-v', 'error', '-f', 'rawvideo', '-pixel_format',
                        'yuv420p' if depth == 8 else 'yuv420p10le', '-video_size', '64x64',
                        '-framerate', '1', '-color_range', 'pc' if full else 'tv', '-i', str(source),
                        '-frames:v', '1', '-c:v', 'libx265', '-profile:v', 'main' if depth == 8 else 'main10',
                        '-crf', '18', '-x265-params', params, '-f', 'hevc', '-y', str(stream)])
                    codec.run([codec.FFMPEG, '-v', 'error', '-i', str(stream), '-c:v', 'copy',
                        '-tag:v', 'hvc1', '-y', str(container)])
                    probe = json.loads(codec.run([os.environ.get('FFPROBE', 'ffprobe'), '-v', 'error',
                        '-select_streams', 'v:0', '-show_entries',
                        'stream=extradata,color_primaries,color_transfer,color_space,color_range',
                        '-show_data', '-of', 'json', str(container)]))['streams'][0]
                    assert probe['color_primaries'] == 'bt2020' and probe['color_transfer'] == name_trc
                    assert probe['color_space'] == 'bt2020nc' and probe['color_range'] == ('pc' if full else 'tv')
                    hvcc = bytes.fromhex(''.join(line.split(':', 1)[1].split('  ', 1)[0].strip()
                        for line in probe['extradata'].splitlines() if ':' in line))
                    slices = [unit for unit in codec.nals(stream.read_bytes()) if ((unit[0] >> 1) & 63) <= 31]
                    assert len(slices) == 1 and hvcc[1] & 31 == (1 if depth == 8 else 2)
                    sample = b''.join(len(unit).to_bytes(4, 'big') + unit for unit in slices)
                    checksums = codec.oracle(hvcc, sample, depth, full, tmp)
                    text += codec.array('hdr_' + name + '_hvcc', hvcc) + codec.array('hdr_' + name + '_sample', sample)
                    cases.append(dict(name=name, depth=depth, full=full, transfer=transfer, crc=checksums,
                        hvcc_sha256=hashlib.sha256(hvcc).hexdigest(), sample_sha256=hashlib.sha256(sample).hexdigest()))
    text += 'static const hdr_codec_case_t hdr_codec_cases[] = {\n'
    for case in cases:
        n = case['name']
        text += ('   {{"%s", hdr_%s_hvcc, sizeof(hdr_%s_hvcc), hdr_%s_sample, sizeof(hdr_%s_sample), '
                 '%d, %d, {%s}}, %d},\n') % (n, n, n, n, n, case['depth'], case['full'],
                    ', '.join('0x%08xu' % value for value in case['crc']), case['transfer'])
    text += '};\n'
    (HERE/'hdr_codec_data.h').write_text(text, encoding='utf8', newline='\n')
    (HERE/'hdr_codec_fixtures.json').write_text(json.dumps(dict(width=64, height=64, cases=cases,
        header_sha256=hashlib.sha256(text.encode()).hexdigest(),
        ffmpeg_version=codec.run([codec.FFMPEG, '-version']).decode().splitlines()[0]), indent=2) + '\n',
        encoding='utf8', newline='\n')


def verify():
    header = (HERE/'hdr_codec_data.h').read_bytes().replace(b'\r\n', b'\n')
    manifest = json.loads((HERE/'hdr_codec_fixtures.json').read_text())
    assert hashlib.sha256(header).hexdigest() == manifest['header_sha256']
    arrays = {name: bytes(int(value, 16) for value in re.findall(r'0x([0-9a-f]{2})', body))
        for name, body in re.findall(r'static const uint8_t (\w+)\[\] = \{(.*?)\};', header.decode(), re.S)}
    with tempfile.TemporaryDirectory(prefix='vt-hdr-oracle-') as directory:
        for case in manifest['cases']:
            hvcc, sample = (arrays['hdr_' + case['name'] + suffix] for suffix in ('_hvcc', '_sample'))
            assert hashlib.sha256(hvcc).hexdigest() == case['hvcc_sha256']
            assert hashlib.sha256(sample).hexdigest() == case['sample_sha256']
            assert codec.oracle(hvcc, sample, case['depth'], case['full'], Path(directory)) == case['crc']
    print('VideoToolbox HDR corpus: eight coded PQ/HLG Main/Main10 fixtures match FFmpeg planes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--generate', action='store_true')
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    if args.generate:
        generate()
    if args.verify:
        verify()
    if not args.generate and not args.verify:
        parser.error('choose --generate or --verify')
